// a source: entry gets no generated type, but its keep line
func TestGenSkipsSourceEntries(t *testing.T) {
	c, obs := mixed(t)
	outs, err := gen.Plan(c, obs, nil)
	if err != nil {
		t.Fatal(err)
	}
	for _, o := range outs {
		if o.Lang == "" {
			continue
		}
		for _, bad := range []string{"kube_pod_info", "KubePodInfo", "Uid"} {
			if strings.Contains(string(o.Content), bad) {
				t.Errorf("%s: generated code names the source entry (%s)", o.Path, bad)
			}
		}
		if o.Lang == "go" && !strings.Contains(string(o.Content), "checkout.charges") && strings.HasSuffix(o.Path, ".go") && strings.Contains(o.Path, "signals") {
			t.Errorf("%s: own metric lost", o.Path)
		}
	}
	for _, o := range outs {
		if strings.HasSuffix(o.Path, "aggregation.yaml") && strings.Contains(string(o.Content), "kube_pod_info") {
			t.Errorf("aggregation names the source entry:\n%s", o.Content)
		}
	}
}

// gen --check reports a missing, edited or stale keep.yaml like the other generated files
func TestKeepFileCheck(t *testing.T) {
	c, obs := mixed(t)
	root := gen.Root(obs)
	outs, err := gen.Plan(c, obs, nil)
	if err != nil {
		t.Fatal(err)
	}
	probs, err := gen.Check(root, outs, c)
	if err != nil || len(probs) == 0 || !strings.Contains(strings.Join(probs, "\n"), "observability/contract/keep.yaml: [gen-missing]") {
		t.Fatalf("missing keep.yaml: %v %v", probs, err)
	}
	if err := gen.Write(root, outs); err != nil {
		t.Fatal(err)
	}
	if probs, err = gen.Check(root, outs, c); err != nil || len(probs) != 0 {
		t.Fatalf("baseline: %v %v", probs, err)
	}
	kp := filepath.Join(obs, "contract", "keep.yaml")
	b, _ := os.ReadFile(kp)
	if err := os.WriteFile(kp, []byte(strings.Replace(string(b), "  - kube_pod_info\n", "  - kube_pod_info\n  - sneaked_in\n", 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	probs, _ = gen.Check(root, outs, c)
	if len(probs) != 1 || !strings.Contains(probs[0], "contract/keep.yaml: [gen-edited]") || !strings.Contains(probs[0], "sneaked_in") {
		t.Fatalf("edited keep.yaml: %v", probs)
	}
	// stale: the contract changes, the file keeps the old hash
	if err := os.WriteFile(kp, b, 0o644); err != nil {
		t.Fatal(err)
	}
	c2, err := contract.Parse(c.File, []byte(strings.Replace(mixedDoc, "min: 1, max: 10", "min: 2, max: 10", 1)))
	if err != nil {
		t.Fatal(err)
	}
	outs2, err := gen.Plan(c2, obs, nil)
	if err != nil {
		t.Fatal(err)
	}
	probs, _ = gen.Check(root, outs2, c2)
	if !strings.Contains(strings.Join(probs, "\n"), "contract/keep.yaml: [gen-stale]") {
		t.Fatalf("stale keep.yaml: %v", probs)
	}
}

// Golden: the keep list of a contract copied from the platform cluster draft (names made up where
// a real landscape name appears) is the committed one.
func TestKeepGoldenFromClusterDraft(t *testing.T) {
	dir := testfix.Path(t, "fixtures", "gen", "ok-source-cluster", "observability")
	c, err := contract.LoadValid(filepath.Join(dir, "contract.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	c.File = "observability/contract.yaml"
	if os.Getenv("OBS_UPDATE_GOLDEN") == "1" {
		if err := os.WriteFile(filepath.Join(dir, "contract", "keep.yaml"), gen.Keep(c), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(filepath.Join(dir, "contract", "keep.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	if got := gen.Keep(c); string(got) != string(want) {
		t.Fatalf("keep.yaml differs from the golden file (OBS_UPDATE_GOLDEN=1 rewrites it):\n%s", got)
	}
	if n := len(c.MetricOrder); n != 32 {
		t.Fatalf("fixture has %d entries, want the 32 of the draft", n)
	}
	// every entry has a source, so the generators see nothing
	if own := c.Own(); len(own.MetricOrder) != 0 {
		t.Fatalf("own metrics: %v", own.MetricOrder)
	}
}

// A source: entry whose enum has an empty value (” for a pod with no priority class) must not reach any
// generator: Go once failed with "declared twice" on it, and every language would name the type.
func TestGenSkipsSourceOnlyEnumWithEmptyValue(t *testing.T) {
	const doc = `service: s
types:
  priority_class: { kind: enum, values: ['', system-critical, batch] }
  lane: { kind: enum, values: [a, b] }
generate:
  - { lang: go, out: gen/go/signals, package: signals }
  - { lang: dotnet, out: gen/dotnet/Signals, namespace: S.Signals }
  - { lang: dart, out: gen/dart/lib/src/signals, package: s_signals }
  - { lang: bun, out: gen/bun/src/signals }
metrics:
  checkout.charges:
    kind: counter
    budget: 2
    labels: { lane: lane }
  kube_pod_info:
    source: kube-state-metrics
    kind: gauge
    budget: 6
    used_by: [hub/dash/pods]
    labels: { priority_class: priority_class }
`
	dir := t.TempDir()
	obs := filepath.Join(dir, "observability")
	if err := os.MkdirAll(obs, 0o755); err != nil {
		t.Fatal(err)
	}
	p := filepath.Join(obs, "contract.yaml")
	if err := os.WriteFile(p, []byte(doc), 0o644); err != nil {
		t.Fatal(err)
	}
	c, err := contract.LoadValid(p)
	if err != nil {
		t.Fatalf("source-only enum with an empty value refused: %v", err)
	}
	outs, err := gen.Plan(c, obs, nil)
	if err != nil {
		t.Fatal(err)
	}
	langs := map[string]bool{}
	for _, o := range outs {
		if o.Lang == "" {
			continue
		}
		langs[o.Lang] = true
		low := strings.ToLower(string(o.Content))
		for _, bad := range []string{"priority", "system-critical", "kube_pod_info"} {
			if strings.Contains(low, bad) {
				t.Errorf("%s (%s): generated code names the source-only type (%s)", o.Path, o.Lang, bad)
			}
		}
	}
	for _, l := range []string{"go", "dotnet", "dart", "bun"} {
		if !langs[l] {
			t.Errorf("no output for %s", l)
		}
	}
}
