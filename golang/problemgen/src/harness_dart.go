package main

import (
	"fmt"
	"math"
	"strconv"
	"strings"
)

func init() { harnesses["dart"] = emitDartHarness }

// dartPkg is the package name the conformance project (lang-dart.sh) gives itself.
const dartPkg = "conftest"

// dartLit renders a vector value as a Dart expression of the generated type.
func dartLit(m *Module, t FieldType, v *JV) string { return dartLitP(m, "g", t, v) }

// dartLitP is dartLit with generated names under the import prefix pfx.
func dartLitP(m *Module, pfx string, t FieldType, v *JV) string {
	switch t.Kind {
	case KString:
		return dartStrUnits(v.Str)
	case KInteger:
		return v.Num
	case KInt64:
		s := v.GoString()
		if s == "-9223372036854775808" {
			return "(-9223372036854775807 - 1)"
		}
		return s
	case KNumber:
		if v.Kind == 'o' {
			f, _ := v.Get("$float")
			switch f.GoString() {
			case "NaN":
				return "double.nan"
			case "Infinity":
				return "double.infinity"
			case "-Infinity":
				return "double.negativeInfinity"
			case "-0":
				return "-0.0"
			}
		}
		f, _ := strconv.ParseFloat(v.Num, 64)
		if math.IsInf(f, 1) {
			return "double.infinity"
		}
		if math.IsInf(f, -1) {
			return "double.negativeInfinity"
		}
		s := strconv.FormatFloat(f, 'g', -1, 64)
		if !strings.ContainsAny(s, ".eE") {
			s += ".0"
		}
		return s
	case KBoolean:
		return strconv.FormatBool(v.Bool)
	case KDateTime:
		tm, err := parseCanonicalDateTime(v.GoString())
		if err != nil {
			// not a valid instant: every language must refuse before this point
			return "DateTime.utc(0)"
		}
		u := tm.UTC()
		ns := u.Nanosecond()
		return fmt.Sprintf("DateTime.utc(%d, %d, %d, %d, %d, %d, %d, %d)", u.Year(), int(u.Month()), u.Day(), u.Hour(), u.Minute(), u.Second(), ns/1_000_000, (ns/1000)%1000)
	case KArray:
		var parts []string
		for _, e := range v.Arr {
			parts = append(parts, dartLitP(m, pfx, *t.Items, e))
		}
		return "<" + dartTypeP(m, pfx, *t.Items) + ">[" + strings.Join(parts, ", ") + "]"
	case KRef:
		nt := m.TypeByName(t.Ref)
		if nt.IsEnum {
			return pfx + "." + nt.Name + "." + dartEnumConst(v.GoString())
		}
		return dartCtorP(m, pfx, pfx+"."+nt.Name, nt.Fields, v)
	}
	return "null"
}

func dartTypeQ(m *Module, t FieldType) string { return dartTypeP(m, "g", t) }

func dartTypeP(m *Module, pfx string, t FieldType) string {
	switch t.Kind {
	case KString:
		return "String"
	case KInteger, KInt64:
		return "int"
	case KNumber:
		return "double"
	case KBoolean:
		return "bool"
	case KDateTime:
		return "DateTime"
	case KArray:
		return "List<" + dartTypeP(m, pfx, *t.Items) + ">"
	case KRef:
		return pfx + "." + t.Ref
	}
	return "Object"
}

// dartCtor renders Name(field: value, ...) with every required field and each present optional.
func dartCtor(m *Module, name string, fields []*Field, data *JV, _ bool) string {
	return dartCtorP(m, "g", name, fields, data)
}

func dartCtorP(m *Module, pfx, name string, fields []*Field, data *JV) string {
	var args []string
	for _, f := range fields {
		v, ok := data.Get(f.Name)
		present := ok && v.Kind != 'z'
		if !f.Optional || present {
			args = append(args, f.Name+": "+dartLitP(m, pfx, f.Type, v))
		}
	}
	return name + "(" + strings.Join(args, ", ") + ")"
}

func dartCaseExpr(m *Module, c VCase) string {
	var p *Problem
	for _, q := range m.Problems {
		if q.ID == c.Problem {
			p = q
		}
	}
	data := c.Data
	if data == nil {
		data = &JV{Kind: 'o'}
	}
	e := dartCtor(m, "g."+Pascal(p.ID), p.Data, data, true)
	if c.Instance != "" {
		e = strings.TrimSuffix(e, ")")
		if !strings.HasSuffix(e, "(") {
			e += ", "
		}
		e += "instance: " + dartStr(c.Instance) + ")"
	}
	return e
}

func emitDartHarness(m *Module, cfg *Config, o Outputs, v *Vectors) string {
	file := o.Dart.File
	rel := file
	if i := strings.Index(file, "/lib/"); i >= 0 {
		rel = file[i+len("/lib/"):]
	}
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...); b.WriteByte('\n') }
	w("// Code generated by problemgen conformance emit --lang dart. DO NOT EDIT.")
	w("// ignore_for_file: type=lint")
	w("import 'dart:convert';")
	w("import 'dart:io';")
	w("")
	w("import '%s' as rt;", o.Dart.Runtime)
	w("import 'package:%s/%s' as g;", dartPkg, rel)
	w("")
	w("final site = rt.Site(%s, %s);", dartStr(v.Portal), dartStr(v.Landscape))
	w("")
	w("void out(Map<String, Object?> m) => stdout.writeln(jsonEncode(m));")
	w("")
	w("void emit(String name, g.Problem p) {")
	w("  try {")
	w("    final wire = rt.marshal(p, site);")
	w("    out({'name': name, 'ok': true, 'wire': wire, 'log': p.logLine()});")
	w("  } on ArgumentError catch (e) {")
	w("    out({'name': name, 'ok': false, 'error': e.toString()});")
	w("  }")
	w("}")
	w("")
	w("void parseFile(String path) {")
	w("  for (final line in File(path).readAsLinesSync()) {")
	w("    if (line.trim().isEmpty) continue;")
	w("    final inp = jsonDecode(line) as Map<String, dynamic>;")
	w("    final name = inp['name'] as String;")
	w("    final p = g.Problem.parse(inp['wire'] as String);")
	w("    if (p == null) {")
	w("      out({'name': name, 'ok': false, 'variant': 'not-problem', 'error': 'not an RFC 9457 problem'});")
	w("      continue;")
	w("    }")
	w("    switch (p) {")
	w("      case g.Unknown(:final reason):")
	w("        out({'name': name, 'ok': false, 'variant': 'unknown', 'error': reason});")
	w("      default:")
	w("        try {")
	w("          out({'name': name, 'ok': true, 'variant': p.meta.id, 'rewire': rt.marshal(p, site)});")
	w("        } on ArgumentError catch (e) {")
	w("          out({'name': name, 'ok': false, 'variant': p.meta.id, 'error': e.toString()});")
	w("        }")
	w("    }")
	w("  }")
	w("}")
	w("")
	w("void bench(int n) {")
	w("  final cases = <(String, g.Problem Function())>[")
	for _, c := range v.Cases {
		if c.Name == "generic-entity-not-found" || c.Name == "every-basic" {
			w("    (%s, () => %s),", dartStr(c.Name), dartCaseExpr(m, c))
		}
	}
	w("  ];")
	w("  for (final (name, mk) in cases) {")
	w("    for (var i = 0; i < n ~/ 10; i++) {")
	w("      rt.marshal(mk(), site); // warm-up")
	w("    }")
	w("    final bytes = utf8.encode(rt.marshal(mk(), site)).length;")
	w("    var total = 0;")
	w("    final sw = Stopwatch()..start();")
	w("    for (var i = 0; i < n; i++) {")
	w("      total += rt.marshal(mk(), site).length;")
	w("    }")
	w("    sw.stop();")
	w("    final ns = sw.elapsedTicks * 1e9 / sw.frequency / n;")
	w("    if (total <= 0) throw StateError('unreachable');")
	w("    stdout.writeln('{\"lang\":\"dart\",\"case\":${jsonEncode(name)},\"n\":$n,\"nsPerOp\":${ns.toStringAsFixed(1)},\"bytes\":$bytes}');")
	w("  }")
	w("}")
	w("")
	w("void main(List<String> args) {")
	w("  if (args.length > 1 && args[0] == 'parse') {")
	w("    parseFile(args[1]);")
	w("    return;")
	w("  }")
	w("  if (args.isNotEmpty && args[0] == 'bench') {")
	w("    bench(1000000);")
	w("    return;")
	w("  }")
	for _, c := range v.Cases {
		w("  emit(%s, %s);", dartStr(c.Name), dartCaseExpr(m, c))
	}
	w("}")
	return b.String()
}

func init() { batchHarnesses["dart"] = emitDartBatch }

func dartCaseExprP(m *Module, pfx string, c VCase) string {
	var p *Problem
	for _, q := range m.Problems {
		if q.ID == c.Problem {
			p = q
		}
	}
	data := c.Data
	if data == nil {
		data = &JV{Kind: 'o'}
	}
	e := dartCtorP(m, pfx, pfx+"."+Pascal(p.ID), p.Data, data)
	if c.Instance != "" {
		e = strings.TrimSuffix(e, ")")
		if !strings.HasSuffix(e, "(") {
			e += ", "
		}
		e += "instance: " + dartStr(c.Instance) + ")"
	}
	return e
}

// emitDartBatch is one Dart program (bin/main.dart) for every module of a batch; module
// <key> is imported with the prefix m_<key>.
func emitDartBatch(cfg *Config, mods []BatchModule) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...); b.WriteByte('\n') }
	w("// Code generated by problemgen conformance batch-emit --lang dart. DO NOT EDIT.")
	w("import 'dart:convert';")
	w("import 'dart:io';")
	w("")
	w("import '%s' as rt;", mods[0].Out.Dart.Runtime)
	for _, bm := range mods {
		file := bm.Out.Dart.File
		rel := file
		if i := strings.Index(file, "/lib/"); i >= 0 {
			rel = file[i+len("/lib/"):]
		}
		w("import 'package:%s/%s' as m_%s;", dartPkg, rel, bm.Key)
	}
	w("")
	w("void out(Map<String, Object?> m) => stdout.writeln(jsonEncode(m));")
	w("")
	w("void emit(String name, rt.Site site, rt.Problem Function() mk) {")
	w("  try {")
	w("    final p = mk();")
	w("    final wire = rt.marshal(p, site);")
	w("    out({'name': name, 'ok': true, 'wire': wire, 'log': p.logLine()});")
	w("  } on ArgumentError catch (e) {")
	w("    out({'name': name, 'ok': false, 'error': e.toString()});")
	w("  }")
	w("}")
	w("")
	w("void reemit(String name, rt.Site site, rt.Problem p) {")
	w("  try {")
	w("    out({'name': name, 'ok': true, 'variant': p.meta.id, 'rewire': rt.marshal(p, site)});")
	w("  } on ArgumentError catch (e) {")
	w("    out({'name': name, 'ok': false, 'variant': p.meta.id, 'error': e.toString()});")
	w("  }")
	w("}")
	w("")
	w("final parsers = <String, void Function(String, String)>{")
	for _, bm := range mods {
		px := "m_" + bm.Key
		w("  %s: (name, wire) {", dartStr(bm.Key))
		w("    final p = %s.Problem.parse(wire);", px)
		w("    if (p == null) {")
		w("      out({'name': name, 'ok': false, 'variant': 'not-problem', 'error': 'not an RFC 9457 problem'});")
		w("      return;")
		w("    }")
		w("    switch (p) {")
		w("      case %s.Unknown(:final reason):", px)
		w("        out({'name': name, 'ok': false, 'variant': 'unknown', 'error': reason});")
		w("      default:")
		w("        reemit(name, rt.Site(%s, %s), p);", dartStr(bm.V.Portal), dartStr(bm.V.Landscape))
		w("    }")
		w("  },")
	}
	w("};")
	w("")
	w("void parseFile(String path) {")
	w("  for (final line in File(path).readAsLinesSync()) {")
	w("    if (line.trim().isEmpty) continue;")
	w("    final inp = jsonDecode(line) as Map<String, dynamic>;")
	w("    final name = inp['name'] as String;")
	w("    final fn = parsers[name.split('/').first];")
	w("    if (fn != null) fn(name, inp['wire'] as String);")
	w("  }")
	w("}")
	w("")
	w("void main(List<String> args) {")
	w("  if (args.length > 1 && args[0] == 'parse') {")
	w("    parseFile(args[1]);")
	w("    return;")
	w("  }")
	for _, bm := range mods {
		for _, c := range bm.V.Cases {
			w("  emit(%s, rt.Site(%s, %s), () => %s);", dartStr(bm.Key+"/"+c.Name), dartStr(bm.V.Portal), dartStr(bm.V.Landscape), dartCaseExprP(bm.M, "m_"+bm.Key, c))
		}
	}
	w("}")
	return b.String()
}
