// goLit renders a vector value as a Go expression of the generated type.
func goLit(m *Module, pkg string, t FieldType, v *JV) string {
	switch t.Kind {
	case KString:
		return strconv.Quote(v.GoString())
	case KInteger, KInt64:
		if t.Kind == KInt64 {
			return "int64(" + v.GoString() + ")"
		}
		return "int64(" + v.Num + ")"
	case KNumber:
		if v.Kind == 'o' {
			f, _ := v.Get("$float")
			switch f.GoString() {
			case "NaN":
				return "math.NaN()"
			case "Infinity":
				return "math.Inf(1)"
			case "-Infinity":
				return "math.Inf(-1)"
			case "-0":
				return "math.Copysign(0, -1)"
			}
		}
		f, _ := strconv.ParseFloat(v.Num, 64)
		if math.IsInf(f, 0) {
			return "math.Inf(1)"
		}
		return "float64(" + strconv.FormatFloat(f, 'g', -1, 64) + ")"
	case KBoolean:
		return strconv.FormatBool(v.Bool)
	case KDateTime:
		return "mustTime(" + strconv.Quote(v.GoString()) + ")"
	case KArray:
		var parts []string
		for _, e := range v.Arr {
			parts = append(parts, goLit(m, pkg, *t.Items, e))
		}
		return "[]" + goTypeQ(m, pkg, *t.Items) + "{" + strings.Join(parts, ", ") + "}"
	case KRef:
		nt := m.TypeByName(t.Ref)
		if nt.IsEnum {
			return pkg + "." + nt.Name + Pascal(v.GoString())
		}
		return goCtor(m, pkg, nt.Name, nt.Fields, v)
	}
	return "nil"
}

func goTypeQ(m *Module, pkg string, t FieldType) string {
	switch t.Kind {
	case KString:
		return "string"
	case KInteger, KInt64:
		return "int64"
	case KNumber:
		return "float64"
	case KBoolean:
		return "bool"
	case KDateTime:
		return "time.Time"
	case KRef:
		return pkg + "." + t.Ref
	}
	return "any"
}

// goCtor renders New<Name>(required...) followed by .With<Opt>(...) for present optionals.
func goCtor(m *Module, pkg, name string, fields []*Field, data *JV) string {
	var args, withs []string
	for _, f := range fields {
		v, ok := data.Get(f.Name)
		present := ok && v.Kind != 'z'
		if !f.Optional {
			args = append(args, goLit(m, pkg, f.Type, v))
		} else if present {
			withs = append(withs, ".With"+Pascal(f.Name)+"("+goLit(m, pkg, f.Type, v)+")")
		}
	}
	return pkg + ".New" + name + "(" + strings.Join(args, ", ") + ")" + strings.Join(withs, "")
}

