const mixedDoc = `service: mixed
types:
  pod: { kind: estimate, min: 1, max: 10, churn_per_day: 2 }
  lane: { kind: enum, values: [a, b] }
generate:
  - { lang: go, out: gen/go }
metrics:
  checkout.charges:
    kind: counter
    budget: 2
    labels: { lane: lane }
  checkout.charge.duration:
    kind: histogram
    unit: seconds
  kube_pod_info:
    source: kube-state-metrics
    kind: gauge
    budget: 10
    used_by: [hub/dash/pods]
    labels:
      pod: pod
      uid: { follows: pod }
platform_metrics:
  http.server.request.duration: [http.route]
`

func mixed(t *testing.T) (*contract.Contract, string) {
	t.Helper()
	dir := t.TempDir()
	obs := filepath.Join(dir, "observability")
	if err := os.MkdirAll(obs, 0o755); err != nil {
		t.Fatal(err)
	}
	p := filepath.Join(obs, "contract.yaml")
	if err := os.WriteFile(p, []byte(mixedDoc), 0o644); err != nil {
		t.Fatal(err)
	}
	c, err := contract.LoadValid(p)
	if err != nil {
		t.Fatal(err)
	}
	return c, obs
}

