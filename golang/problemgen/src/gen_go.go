package main

import (
	"fmt"
	"strconv"
	"strings"
)

// GenerateGo renders the Go output for one module.
func GenerateGo(m *Module, cfg *Config, o *GoOut, source string) string {
	g := &goGen{m: m, cfg: cfg, o: o}
	return g.file(source)
}

type goGen struct {
	m   *Module
	cfg *Config
	o   *GoOut
	b   strings.Builder
}

func (g *goGen) p(f string, a ...any) { fmt.Fprintf(&g.b, f, a...); g.b.WriteByte('\n') }

func (g *goGen) usesTime() bool {
	var uses func(t FieldType) bool
	uses = func(t FieldType) bool {
		switch t.Kind {
		case KDateTime:
			return true
		case KArray:
			return uses(*t.Items)
		}
		return false
	}
	for _, t := range g.m.Types {
		for _, f := range t.Fields {
			if uses(f.Type) {
				return true
			}
		}
	}
	for _, p := range g.m.Problems {
		for _, f := range p.Data {
			if uses(f.Type) {
				return true
			}
		}
	}
	return false
}

func (g *goGen) file(source string) string {
	g.p("// Code generated by problemgen %s. DO NOT EDIT.", toolVersion)
	g.p("// source: %s sha256:%s", source, g.m.Def.SHA256)
	g.p("")
	g.p("// Package %s holds the problems of %s/%s module %s, version %s.", g.o.Package, g.cfg.Platform, g.cfg.Service, g.m.Def.Module, g.m.Def.Version)
	g.p("// These are API-layer values: none of them is an error, and domain packages must not")
	g.p("// import this package (enforced by depguard in the consuming service).")
	g.p("package %s", g.o.Package)
	g.p("")
	g.p("import (")
	g.p("\t\"encoding/json\"")
	g.p("\t\"strconv\"")
	g.p("\t\"strings\"")
	if g.usesTime() {
		g.p("\t\"time\"")
	}
	g.p("")
	g.p("\trt %q", g.o.Runtime)
	g.p(")")
	g.p("")
	g.p("var (")
	g.p("\t_ = json.RawMessage(nil)")
	g.p("\t_ = strconv.Itoa")
	g.p("\t_ strings.Builder")
	g.p(")")
	g.p("")
	g.p("// Problem is the closed set of problems of this module, plus Unknown for anything else")
	g.p("// a client receives. It is not an error.")
	g.p("//")
	g.p("//sumtype:decl")
	g.p("type Problem interface {")
	g.p("\trt.Problem")
	g.p("\tisProblem()")
	g.p("}")
	g.p("")
	for _, t := range g.m.Types {
		g.namedType(t)
	}
	for _, p := range g.m.Problems {
		g.problem(p)
	}
	g.unknown()
	g.parse()
	return g.b.String()
}

func (g *goGen) goType(t FieldType) string {
	switch t.Kind {
	case KString:
		return "string"
	case KInteger, KInt64:
		return "int64"
	case KNumber:
		return "float64"
	case KBoolean:
		return "bool"
	case KDateTime:
		return "time.Time"
	case KArray:
		return "[]" + g.goType(*t.Items)
	case KRef:
		return t.Ref
	}
	return "any"
}

func (g *goGen) storeType(f *Field) string {
	if f.Optional {
		return "*" + g.goType(f.Type)
	}
	return g.goType(f.Type)
}

func goParam(name string) string { return name }

func hasRequired(fields []*Field) bool {
	for _, f := range fields {
		if !f.Optional {
			return true
		}
	}
	return false
}

func (g *goGen) isEnum(t FieldType) bool {
	if t.Kind != KRef {
		return false
	}
	nt := g.m.TypeByName(t.Ref)
	return nt != nil && nt.IsEnum
}

func (g *goGen) namedType(t *NamedType) {
	if t.Description != "" {
		g.p("// %s: %s", t.Name, t.Description)
	}
	if t.IsEnum {
		g.p("type %s string", t.Name)
		g.p("")
		g.p("const (")
		for _, v := range t.Values {
			g.p("\t%s%s %s = %q", t.Name, Pascal(v), t.Name, v)
		}
		g.p(")")
		g.p("")
		g.p("// Valid reports whether v is a declared value of %s.", t.Name)
		g.p("func (v %s) Valid() bool {", t.Name)
		g.p("\tswitch v {")
		var cs []string
		for _, v := range t.Values {
			cs = append(cs, t.Name+Pascal(v))
		}
		g.p("\tcase %s:", strings.Join(cs, ", "))
		g.p("\t\treturn true")
		g.p("\t}")
		g.p("\treturn false")
		g.p("}")
		g.p("")
		return
	}
	g.p("type %s struct {", t.Name)
	for _, f := range t.Fields {
		g.p("\t%s %s", f.Name, g.storeType(f))
	}
	if hasRequired(t.Fields) {
		g.p("\tbuilt bool // set by New%s/decode; a zero-value literal is refused when serialised", t.Name)
	}
	g.p("}")
	g.p("")
	g.constructor(t.Name, t.Fields, "", false)
	g.accessors(t.Name, t.Fields)
	g.p("func (v %s) writeJSON(w *rt.Writer) {", t.Name)
	if hasRequired(t.Fields) {
		g.p("\tif !v.built {")
		g.p("\t\tw.Fail(rt.ErrNotConstructed(%q))", t.Name)
		g.p("\t}")
	}
	g.p("\tw.BeginObject()")
	for _, f := range t.Fields {
		g.writeField(f, "v")
	}
	g.p("\tw.EndObject()")
	g.p("}")
	g.p("")
	g.p("func decode%s(r json.RawMessage) (%s, error) {", t.Name, t.Name)
	if hasRequired(t.Fields) {
		g.p("\tv := %s{built: true}", t.Name)
	} else {
		g.p("\tvar v %s", t.Name)
	}
	g.p("\tm, err := rt.Fields(r)")
	g.p("\tif err != nil {")
	g.p("\t\treturn v, err")
	g.p("\t}")
	for _, f := range t.Fields {
		g.decodeField(f, "v", t.Name)
	}
	g.p("\treturn v, nil")
	g.p("}")
	g.p("")
}

func (g *goGen) constructor(name string, fields []*Field, metaVar string, isProblem bool) {
	var params, assigns []string
	for _, f := range fields {
		if f.Optional {
			continue
		}
		params = append(params, goParam(f.Name)+" "+g.goType(f.Type))
		assigns = append(assigns, f.Name+": "+goParam(f.Name))
	}
	g.p("// New%s builds a %s. Required fields are parameters, in declaration order;", name, name)
	g.p("// optional fields are set with With* methods.")
	g.p("func New%s(%s) %s {", name, strings.Join(params, ", "), name)
	if hasRequired(fields) {
		assigns = append(assigns, "built: true")
	}
	g.p("\treturn %s{%s}", name, strings.Join(assigns, ", "))
	g.p("}")
	g.p("")
}

func (g *goGen) accessors(name string, fields []*Field) {
	for _, f := range fields {
		pn := Pascal(f.Name)
		if f.Private {
			continue
		}
		if f.Deprecated != "" {
			g.p("// Deprecated: %s", f.Deprecated)
		}
		if f.Optional {
			g.p("// %s returns the optional field %q.", pn, f.Name)
			g.p("func (v %s) %s() (%s, bool) {", name, pn, g.goType(f.Type))
			g.p("\tif v.%s == nil {", f.Name)
			g.p("\t\tvar zero %s", g.goType(f.Type))
			g.p("\t\treturn zero, false")
			g.p("\t}")
			g.p("\treturn *v.%s, true", f.Name)
			g.p("}")
		} else {
			g.p("// %s returns the field %q.", pn, f.Name)
			g.p("func (v %s) %s() %s { return v.%s }", name, pn, g.goType(f.Type), f.Name)
		}
		g.p("")
	}
	for _, f := range fields {
		if !f.Optional {
			continue
		}
		pn := Pascal(f.Name)
		g.p("// With%s returns a copy with the optional field %q set.", pn, f.Name)
		g.p("func (v %s) With%s(x %s) %s {", name, pn, g.goType(f.Type), name)
		g.p("\tv.%s = &x", f.Name)
		g.p("\treturn v")
		g.p("}")
		g.p("")
	}
}

func (g *goGen) writeValue(expr string, t FieldType, indent string) {
	switch t.Kind {
	case KString:
		g.p("%sw.String(%s)", indent, expr)
	case KInteger:
		g.p("%sw.Integer(%s)", indent, expr)
	case KInt64:
		g.p("%sw.Int64(%s)", indent, expr)
	case KNumber:
		g.p("%sw.Number(%s)", indent, expr)
	case KBoolean:
		g.p("%sw.Bool(%s)", indent, expr)
	case KDateTime:
		g.p("%sw.DateTime(%s)", indent, expr)
	case KArray:
		g.p("%sw.BeginArray()", indent)
		g.p("%sfor _, e := range %s {", indent, expr)
		g.writeValue("e", *t.Items, indent+"\t")
		g.p("%s}", indent)
		g.p("%sw.EndArray()", indent)
	case KRef:
		if g.isEnum(t) {
			g.p("%sw.Enum(string(%s), %s.Valid())", indent, expr, expr)
		} else {
			g.p("%s%s.writeJSON(w)", indent, expr)
		}
	}
}

func (g *goGen) writeField(f *Field, recv string) {
	if f.Private {
		return
	}
	if f.Optional {
		g.p("\tif %s.%s != nil {", recv, f.Name)
		g.p("\t\tw.Key(%q)", f.Name)
		g.writeValue("(*"+recv+"."+f.Name+")", f.Type, "\t\t")
		g.p("\t}")
		return
	}
	g.p("\tw.Key(%q)", f.Name)
	g.writeValue(recv+"."+f.Name, f.Type, "\t")
}

// decodeExpr returns Go statements decoding raw expression `raw` into a fresh variable `out`.
func (g *goGen) decodeInto(out, raw string, t FieldType, indent, ctx string) {
	switch t.Kind {
	case KString:
		g.p("%s%s, err := rt.DecodeString(%s)", indent, out, raw)
	case KInteger:
		g.p("%s%s, err := rt.DecodeInteger(%s)", indent, out, raw)
	case KInt64:
		g.p("%s%s, err := rt.DecodeInt64(%s)", indent, out, raw)
	case KNumber:
		g.p("%s%s, err := rt.DecodeNumber(%s)", indent, out, raw)
	case KBoolean:
		g.p("%s%s, err := rt.DecodeBool(%s)", indent, out, raw)
	case KDateTime:
		g.p("%s%s, err := rt.DecodeDateTime(%s)", indent, out, raw)
	case KArray:
		g.p("%s%sRaw, err := rt.DecodeArray(%s)", indent, out, raw)
		g.p("%sif err != nil {", indent)
		g.p("%s\treturn %s, err", indent, ctx)
		g.p("%s}", indent)
		g.p("%s%s := make(%s, 0, len(%sRaw))", indent, out, g.goType(t), out)
		g.p("%sfor _, er := range %sRaw {", indent, out)
		g.decodeInto("ev", "er", *t.Items, indent+"\t", ctx)
		g.p("%s\tif err != nil {", indent)
		g.p("%s\t\treturn %s, err", indent, ctx)
		g.p("%s\t}", indent)
		g.p("%s\t%s = append(%s, ev)", indent, out, out)
		g.p("%s}", indent)
	case KRef:
		if g.isEnum(t) {
			g.p("%s%sS, err := rt.DecodeString(%s)", indent, out, raw)
			g.p("%s%s := %s(%sS)", indent, out, t.Ref, out)
			g.p("%sif err == nil && !%s.Valid() {", indent, out)
			g.p("%s\terr = errInvalid(%q, %sS)", indent, t.Ref, out)
			g.p("%s}", indent)
		} else {
			g.p("%s%s, err := decode%s(%s)", indent, out, t.Ref, raw)
		}
	}
}

func (g *goGen) decodeField(f *Field, recv, ctxName string) {
	if f.Private {
		return
	}
	g.p("\tif r, ok := m[%q]; ok {", f.Name)
	g.decodeInto("x", "r", f.Type, "\t\t", recv)
	g.p("\t\tif err != nil {")
	g.p("\t\t\treturn %s, errField(%q, err)", recv, f.Name)
	g.p("\t\t}")
	if f.Optional {
		g.p("\t\t%s.%s = &x", recv, f.Name)
	} else {
		g.p("\t\t%s.%s = x", recv, f.Name)
	}
	if !f.Optional {
		g.p("\t} else {")
		g.p("\t\treturn %s, errMissing(%q)", recv, f.Name)
	}
	g.p("\t}")
}

func (g *goGen) templateExpr(p *Problem, part Part, forLog bool) string {
	f := p.Field(part.Field)
	wrap := func(s string) string {
		if forLog {
			return "rt.LogValue(" + s + ")"
		}
		return "rt.DetailValue(" + s + ")"
	}
	val := "p." + f.Name
	if f.Optional {
		val = "(*p." + f.Name + ")"
	}
	var s string
	switch {
	case part.Count:
		s = "strconv.Itoa(len(" + val + "))"
	case f.Type.Kind == KString:
		s = wrap(val)
	case f.Type.Kind == KInteger || f.Type.Kind == KInt64:
		s = "strconv.FormatInt(" + val + ", 10)"
	case f.Type.Kind == KNumber:
		s = "rt.TemplateNumber(" + val + ")"
	case f.Type.Kind == KBoolean:
		s = "strconv.FormatBool(" + val + ")"
	case f.Type.Kind == KDateTime:
		s = "rt.FormatDateTime(" + val + ")"
	case g.isEnum(f.Type):
		s = wrap("string(" + val + ")")
	}
	return s
}

func (g *goGen) renderTemplate(p *Problem, t *Template, forLog bool) {
	g.p("\tvar b strings.Builder")
	for _, part := range t.Parts {
		if !part.IsPlaceholder() {
			g.p("\tb.WriteString(%s)", strconv.Quote(part.Lit))
			continue
		}
		f := p.Field(part.Field)
		if f.Optional {
			g.p("\tif p.%s == nil {", f.Name)
			g.p("\t\tb.WriteString(%s)", strconv.Quote(part.Default))
			g.p("\t} else {")
			g.p("\t\tb.WriteString(%s)", g.templateExpr(p, part, forLog))
			g.p("\t}")
		} else {
			g.p("\tb.WriteString(%s)", g.templateExpr(p, part, forLog))
		}
	}
	g.p("\treturn b.String()")
}

func (g *goGen) problem(p *Problem) {
	n := Pascal(p.ID)
	g.p("// %s is %q (%d, %s).", n, p.ID, p.Status, p.Title)
	if p.Description != "" {
		g.p("// %s", p.Description)
	}
	g.p("// detail: %s", p.DetailSrc)
	if p.Deprecated != "" {
		g.p("//")
		g.p("// Deprecated: %s", p.Deprecated)
	}
	g.p("type %s struct {", n)
	for _, f := range p.Data {
		c := ""
		if f.Private {
			c = " // private: log only, never on the wire"
		}
		g.p("\t%s %s%s", f.Name, g.storeType(f), c)
	}
	if hasRequired(p.Data) {
		g.p("\tbuilt    bool // set by New%s/Parse; a zero-value literal is refused when serialised", n)
	}
	g.p("\tinstance string")
	g.p("\tcause    error")
	g.p("\treceived *rt.Received")
	g.p("}")
	g.p("")
	g.p("var meta%s = &rt.Meta{ID: %q, Title: %s, Status: %d, Recoverable: %v, Platform: %q, Service: %q, Module: %q, Version: %q}",
		n, p.ID, strconv.Quote(p.Title), p.Status, p.Recoverable, g.cfg.Platform, g.cfg.Service, g.m.Def.Module, g.m.Def.Version)
	g.p("")
	g.constructor(n, p.Data, "meta"+n, true)
	g.accessors(n, p.Data)
	g.p("// WithInstance returns a copy with the RFC 9457 instance set (set by the API layer).")
	g.p("func (p %s) WithInstance(instance string) %s { p.instance = instance; return p }", n, n)
	g.p("")
	g.p("// WithCause returns a copy carrying the cause for the log hook; it never reaches the wire.")
	g.p("func (p %s) WithCause(cause error) %s { p.cause = cause; return p }", n, n)
	g.p("")
	g.p("func (%s) isProblem() {}", n)
	g.p("")
	g.p("// ProblemMeta returns the fixed description of %s.", n)
	g.p("func (%s) ProblemMeta() *rt.Meta { return meta%s }", n, n)
	g.p("")
	g.p("// InstanceURI returns the RFC 9457 instance (empty when unset).")
	g.p("func (p %s) InstanceURI() string { return p.instance }", n)
	g.p("")
	g.p("// ProblemCause returns the cause passed to WithCause.")
	g.p("func (p %s) ProblemCause() error { return p.cause }", n)
	g.p("")
	g.p("// ReceivedType is the type URI a parsed problem arrived with.")
	g.p("func (p %s) ReceivedType() string {", n)
	g.p("\tif p.received == nil {")
	g.p("\t\treturn \"\"")
	g.p("\t}")
	g.p("\treturn p.received.Type")
	g.p("}")
	g.p("")
	g.p("// RetryAfterSeconds returns the Retry-After hint, if this problem declares one.")
	if p.RetryAfter != "" {
		g.p("func (p %s) RetryAfterSeconds() (int64, bool) { return p.%s, true }", n, p.RetryAfter)
	} else {
		g.p("func (%s) RetryAfterSeconds() (int64, bool) { return 0, false }", n)
	}
	g.p("")
	g.p("// Detail renders the detail template (or returns the received detail).")
	g.p("func (p %s) Detail() string {", n)
	g.p("\tif p.received != nil {")
	g.p("\t\treturn p.received.Detail")
	g.p("\t}")
	g.renderTemplate(p, p.Detail, false)
	g.p("}")
	g.p("")
	g.p("// LogLine renders the log template. It may contain private fields; it is never sent.")
	g.p("func (p %s) LogLine() string {", n)
	g.renderTemplate(p, p.Log, true)
	g.p("}")
	g.p("")
	g.p("// WriteData writes the public data fields.")
	if len(p.PublicData()) == 0 {
		g.p("func (%s) WriteData(w *rt.Writer) bool { return false }", n)
	} else {
		g.p("func (p %s) WriteData(w *rt.Writer) bool {", n)
		if hasRequired(p.Data) {
			g.p("\tif !p.built {")
			g.p("\t\tw.Fail(rt.ErrNotConstructed(%q))", n)
			g.p("\t}")
		}
		g.p("\tw.BeginObject()")
		for _, f := range p.Data {
			g.writeField(f, "p")
		}
		g.p("\tw.EndObject()")
		g.p("\treturn true")
		g.p("}")
	}
	g.p("")
	g.p("func decode%sProblem(e *rt.Envelope) (%s, error) {", n, n)
	if hasRequired(p.Data) {
		g.p("\tp := %s{built: true, instance: e.Instance, received: &rt.Received{Type: e.Type, Detail: e.Detail}}", n)
	} else {
		g.p("\tp := %s{instance: e.Instance, received: &rt.Received{Type: e.Type, Detail: e.Detail}}", n)
	}
	if len(p.PublicData()) > 0 {
		g.p("\tif e.Data == nil {")
		g.p("\t\te.Data = json.RawMessage(\"{}\")")
		g.p("\t}")
		g.p("\tm, err := rt.Fields(e.Data)")
		g.p("\tif err != nil {")
		g.p("\t\treturn p, err")
		g.p("\t}")
		for _, f := range p.Data {
			g.decodeField(f, "p", n)
		}
	}
	g.p("\treturn p, nil")
	g.p("}")
	g.p("")
}

func (g *goGen) unknown() {
	g.p("// Unknown is a received problem this module does not define (another service, another")
	g.p("// version, an unknown id, or data that does not match). Reason says which.")
	g.p("type Unknown struct {")
	g.p("\tEnvelope *rt.Envelope")
	g.p("\tReason   string")
	g.p("}")
	g.p("")
	g.p("func (*Unknown) isProblem() {}")
	g.p("")
	g.p("// ProblemMeta describes the received problem as far as it is known.")
	g.p("func (u *Unknown) ProblemMeta() *rt.Meta {")
	g.p("\tm := &rt.Meta{Title: u.Envelope.Title, Status: u.Envelope.Status}")
	g.p("\tif a := u.Envelope.Address; a != nil {")
	g.p("\t\tm.ID, m.Platform, m.Service, m.Module, m.Version = a.ID, a.Platform, a.Service, a.Module, a.Version")
	g.p("\t}")
	g.p("\treturn m")
	g.p("}")
	g.p("")
	g.p("// Detail returns the received detail.")
	g.p("func (u *Unknown) Detail() string { return u.Envelope.Detail }")
	g.p("")
	g.p("// LogLine describes the unknown problem.")
	g.p("func (u *Unknown) LogLine() string { return rt.LogValue(\"unknown problem \" + u.Envelope.Type + \": \" + u.Reason) }")
	g.p("")
	g.p("// InstanceURI returns the received instance.")
	g.p("func (u *Unknown) InstanceURI() string { return u.Envelope.Instance }")
	g.p("")
	g.p("// ProblemCause is always nil for a received problem.")
	g.p("func (*Unknown) ProblemCause() error { return nil }")
	g.p("")
	g.p("// RetryAfterSeconds is unknown for an unknown problem.")
	g.p("func (*Unknown) RetryAfterSeconds() (int64, bool) { return 0, false }")
	g.p("")
	g.p("// ReceivedType returns the received type URI.")
	g.p("func (u *Unknown) ReceivedType() string { return u.Envelope.Type }")
	g.p("")
	g.p("// WriteData re-emits nothing: an Unknown is for classification, not re-serialisation.")
	g.p("func (*Unknown) WriteData(w *rt.Writer) bool { return false }")
	g.p("")
}

func (g *goGen) parse() {
	g.p("func errField(name string, err error) error { return &fieldError{name, err.Error()} }")
	g.p("func errMissing(name string) error       { return &fieldError{name, \"required field missing\"} }")
	g.p("func errInvalid(typ, v string) error     { return &fieldError{typ, strconv.Quote(v) + \" is not a declared value\"} }")
	g.p("")
	g.p("type fieldError struct{ field, msg string }")
	g.p("")
	g.p("func (e *fieldError) Error() string { return e.field + \": \" + e.msg }")
	g.p("")
	g.p("// Parse reads a received problem. It returns rt.ErrNotProblem only when the body is not")
	g.p("// an RFC 9457 problem at all; anything this module does not define becomes *Unknown.")
	g.p("func Parse(body []byte) (Problem, error) {")
	g.p("\te, err := rt.ParseEnvelope(body)")
	g.p("\tif err != nil {")
	g.p("\t\treturn nil, err")
	g.p("\t}")
	g.p("\ta := e.Address")
	g.p("\tif a == nil || a.Platform != %q || a.Service != %q || a.Module != %q || a.Version != %q {", g.cfg.Platform, g.cfg.Service, g.m.Def.Module, g.m.Def.Version)
	g.p("\t\treturn &Unknown{Envelope: e, Reason: \"not a problem of %s/%s/%s/%s\"}, nil", g.cfg.Platform, g.cfg.Service, g.m.Def.Module, g.m.Def.Version)
	g.p("\t}")
	g.p("\tswitch a.ID {")
	for _, p := range g.m.Problems {
		n := Pascal(p.ID)
		g.p("\tcase %q:", p.ID)
		g.p("\t\tif e.Status != %d {", p.Status)
		g.p("\t\t\treturn &Unknown{Envelope: e, Reason: \"status does not match %d\"}, nil", p.Status)
		g.p("\t\t}")
		g.p("\t\tp, err := decode%sProblem(e)", n)
		g.p("\t\tif err != nil {")
		g.p("\t\t\treturn &Unknown{Envelope: e, Reason: err.Error()}, nil")
		g.p("\t\t}")
		g.p("\t\treturn p, nil")
	}
	g.p("\t}")
	g.p("\treturn &Unknown{Envelope: e, Reason: \"unknown id \" + strconv.Quote(a.ID)}, nil")
	g.p("}")
}
