package gen

import (
	"fmt"
	"io"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/AtomiCloud/obs/internal/contract"
)

type Orphan struct{ File, Contract string }

var ownerHash = regexp.MustCompile(`^[0-9a-f]{64}$`)

// MissingOwners only recognizes complete generated headers. Discovery's scope
// also fences cleanup, so ignored copies and nested repositories are untouched.
func MissingOwners(scope *contract.Scope, contracts []string, langs ...string) ([]Orphan, error) {
	owners := map[string]bool{}
	for _, file := range contracts {
		owners[scope.Rel(file)] = true
	}
	selected := map[string]bool{}
	for _, lang := range langs {
		for _, name := range strings.Split(lang, ",") {
			if name = strings.TrimSpace(name); name != "" {
				selected[name] = true
			}
		}
	}
	var out []Orphan
	err := filepath.WalkDir(scope.Root, func(file string, entry fs.DirEntry, err error) error {
		if scope.Skips(scope.Root, file) {
			if entry != nil && entry.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if err != nil {
			return fmt.Errorf("generated files: cannot read %s: %w", scope.Rel(file), err)
		}
		if entry.IsDir() {
			switch entry.Name() {
			case ".git", ".direnv", "node_modules", "vendor", ".dart_tool", ".obs-cache", "fixtures", "testdata":
				if file != scope.Root {
					return filepath.SkipDir
				}
			}
			return nil
		}
		if !entry.Type().IsRegular() {
			return nil
		}
		if len(selected) > 0 {
			language := map[string]string{".go": "go", ".ts": "bun", ".cs": "dotnet", ".dart": "dart"}[filepath.Ext(file)]
			if filepath.Ext(file) != ".yaml" && !selected[language] {
				return nil
			}
		}
		// Read only the header, never a potentially large payload.
		f, err := os.Open(file)
		if err != nil {
			return err
		}
		buf := make([]byte, 4096)
		n, rerr := f.Read(buf)
		_ = f.Close()
		if rerr != nil && rerr != io.EOF {
			return fmt.Errorf("generated files: cannot read %s: %w", scope.Rel(file), rerr)
		}
		lines := strings.SplitN(string(buf[:n]), "\n", 4)
		if len(lines) < 4 {
			return nil
		}
		var owner, hash string
		if strings.HasPrefix(lines[0], "# generated by obs gen from ") && strings.HasPrefix(lines[1], "# "+HashPrefix) {
			owner = strings.TrimPrefix(lines[0], "# generated by obs gen from ")
			hash = strings.TrimPrefix(lines[1], "# "+HashPrefix)
		} else {
			prefix := "// "
			if lines[0] == "# "+Marker {
				prefix = "# "
			}
			if lines[0] != prefix+Marker || !strings.HasPrefix(lines[1], prefix+"contract: ") || !strings.HasPrefix(lines[2], prefix+HashPrefix) {
				return nil
			}
			owner = strings.TrimPrefix(lines[1], prefix+"contract: ")
			hash = strings.TrimPrefix(lines[2], prefix+HashPrefix)
		}
		if !ownerHash.MatchString(hash) || path.IsAbs(owner) || owner != path.Clean(owner) || owner == ".." || strings.HasPrefix(owner, "../") || strings.Contains(owner, "\\") || path.Base(owner) != "contract.yaml" {
			return nil
		}
		if owners[owner] {
			return nil
		} // Positive ownership of a current --all header.
		if missingHeaderOwner(file, owner) {
			out = append(out, Orphan{File: file, Contract: owner})
		}
		return nil
	})
	return out, err
}

// Headers written before a Git import can be project-relative. Only report
// absence when every plausible writing base says ENOENT; uncertainty is kept.
func missingHeaderOwner(file, owner string) bool {
	dir := filepath.Dir(file)
	bases := contract.ProjectMarkerRoots(dir)
	if git := GitRoot(dir); git != "" {
		bases = append(bases, git)
	}
	if len(bases) == 0 {
		return false
	}
	for _, base := range bases {
		if _, err := os.Lstat(filepath.Join(base, filepath.FromSlash(owner))); !os.IsNotExist(err) {
			return false
		}
	}
	// An old --all export may have had an unmarked enclosing root. Positive
	// evidence at another ancestor prevents a false orphan; it never proves absence.
	for ancestor := dir; ; ancestor = filepath.Dir(ancestor) {
		if _, err := os.Lstat(filepath.Join(ancestor, filepath.FromSlash(owner))); !os.IsNotExist(err) {
			return false
		}
		if filepath.Dir(ancestor) == ancestor {
			break
		}
	}
	return true
}
