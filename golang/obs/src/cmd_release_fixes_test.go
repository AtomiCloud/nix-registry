func releaseGit(t *testing.T, root string, args ...string) {
	t.Helper()
	cmd := testfix.Git(root, args...)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git %v: %v %s", args, err, out)
	}
}

func TestReleaseMissingContractOrphans(t *testing.T) {
	t.Setenv("GIT_CONFIG_GLOBAL", os.DevNull)
	t.Setenv("GIT_CONFIG_NOSYSTEM", "1")
	for _, lang := range []string{"go", "bun"} {
		for _, change := range []string{"rename", "delete"} {
			t.Run(lang+"/"+change, func(t *testing.T) {
				root := repo(t, map[string]string{"go.mod": "module example.com/shop\ngo 1.27.4\n", "package.json": `{"name":"shop"}`})
				t.Chdir(root)
				releaseGit(t, root, "init", "-q")
				for _, feature := range []string{"orders", "billing"} {
					gen2Write(t, root, "observability/"+feature+"/contract.yaml", "service: shop\nlogs: {Failed: {event: "+feature+".failed, level: error}}\ngenerate: [{lang: "+lang+", out: gen/"+feature+"}]\n")
				}
				if rc, out := obs("gen", "--all"); rc != 0 {
					t.Fatal(out)
				}
				releaseGit(t, root, "add", "observability")
				keep, err := os.ReadFile(filepath.Join(root, "observability/orders/contract/keep.yaml"))
				if err != nil {
					t.Fatal(err)
				}
				gen2Write(t, root, "gen/orders/keep.yaml", string(keep))
				ext := "go"
				if lang == "bun" {
					ext = "ts"
				}
				old := "gen/orders/signals." + ext
				before, err := os.ReadFile(filepath.Join(root, old))
				if err != nil {
					t.Fatal(err)
				}
				gen2Write(t, root, "manual."+ext, "// Code generated by obs gen. DO NOT EDIT.\n// contract: observability/orders/contract.yaml\n// contract-hash: sha256:not-valid\n")
				if change == "rename" {
					releaseGit(t, root, "mv", "observability/orders", "observability/sales")
					gen2Write(t, root, "observability/sales/contract.yaml", "service: shop\nlogs: {Failed: {event: orders.failed, level: error}}\ngenerate: [{lang: "+lang+", out: gen/sales}]\n")
				} else if err := os.RemoveAll(filepath.Join(root, "observability/orders")); err != nil {
					t.Fatal(err)
				}
				if rc, out := obs("gen", "--check", "--all"); rc != 1 || !strings.Contains(out, "[gen-orphan]") || !strings.Contains(out, old) || !strings.Contains(out, "observability/orders/contract.yaml") {
					t.Errorf("missing-contract orphan must name file and owner: rc=%d %s", rc, out)
				}
				if rc, out := obs("gen", "--all"); rc != 0 || !strings.Contains(out, "[gen-orphan]") || !strings.Contains(out, old) || !strings.Contains(out, "remove this file yourself") {
					t.Errorf("regenerate must report stale registration for manual removal: rc=%d %s", rc, out)
				}
				if after, err := os.ReadFile(filepath.Join(root, old)); err != nil || !bytes.Equal(before, after) {
					t.Errorf("report-only generation changed old table: %v", err)
				}
				if after, err := os.ReadFile(filepath.Join(root, "gen/orders/keep.yaml")); err != nil || !bytes.Equal(keep, after) {
					t.Errorf("report-only generation changed old keep file: %v", err)
				}
				if _, err := os.Stat(filepath.Join(root, "manual."+ext)); err != nil {
					t.Errorf("invalid-header user file touched: %v", err)
				}
				if err := os.Remove(filepath.Join(root, old)); err != nil {
					t.Fatal(err)
				}
				if err := os.Remove(filepath.Join(root, "gen/orders/keep.yaml")); err != nil {
					t.Fatal(err)
				}
				if rc, out := obs("gen", "--check", "--all"); rc != 0 {
					t.Fatal(out)
				}
			})
		}
	}
}

