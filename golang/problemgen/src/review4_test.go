func TestR4OverwriteThroughSymlink(t *testing.T) {
	for _, kind := range []string{"file", "directory", "manifest"} {
		t.Run(kind, func(t *testing.T) {
			dir := t.TempDir()
			cfg := r3Svc(t, dir, "a", "a", "{ typescript: { file: out/gen.ts, runtime: r } }")
			ext := filepath.Join(dir, "external")
			os.MkdirAll(ext, 0o755)
			victim := filepath.Join(ext, "notes.txt")
			original := []byte("handwritten, unrelated content\n")
			os.WriteFile(victim, original, 0o644)
			switch kind {
			case "file":
				os.MkdirAll(filepath.Join(dir, "a", "out"), 0o755)
				os.Symlink(victim, filepath.Join(dir, "a", "out", "gen.ts"))
			case "directory":
				victim = filepath.Join(ext, "gen.ts")
				os.WriteFile(victim, original, 0o644)
				os.Symlink(ext, filepath.Join(dir, "a", "out"))
			case "manifest":
				os.Symlink(victim, cfg+".outputs")
			}
			code, out := r3run(t, "generate", "-c", cfg)
			got, _ := os.ReadFile(victim)
			if string(got) != string(original) {
				t.Errorf("unowned victim overwritten (%s), exit %d: %s", victim, code, out)
			}
			if code != 2 || !strings.Contains(out, "symlink") {
				t.Errorf("want a symlink refusal (exit 2), got %d: %s", code, out)
			}
		})
	}
}

func TestR4SymlinkBypassesExistingForeignOwner(t *testing.T) {
	dir := t.TempDir()
	a := r3Svc(t, dir, "a", "a", "{ typescript: { file: ../shared/x.ts, runtime: r } }")
	b := r3Svc(t, dir, "b", "b", "{ typescript: { file: out/gen.ts, runtime: r } }")
	mustGenerate(t, a)
	victim := filepath.Join(dir, "shared", "x.ts")
	original, _ := os.ReadFile(victim)
	os.MkdirAll(filepath.Join(dir, "b", "out"), 0o755)
	os.Symlink(victim, filepath.Join(dir, "b", "out", "gen.ts"))
	code, out := r3run(t, "generate", "-c", b)
	got, _ := os.ReadFile(victim)
	vcode, vout := r3run(t, "verify", "-c", a)
	if string(got) != string(original) || vcode != 0 {
		t.Errorf("overwrote live config a's generated file via b's symlink: exit %d %s; verify a: %d %s", code, out, vcode, vout)
	}
}

func TestR4DeleteAdversarialEntries(t *testing.T) {
	for _, mode := range []string{"absolute", "dotdot", "edited", "symlink-file", "catalog", "case", "owned-dotdot"} {
		t.Run(mode, func(t *testing.T) {
			dir := t.TempDir()
			cfg := r3Svc(t, dir, "a", "a", "{ typescript: { file: gen.ts, runtime: r } }")
			mustGenerate(t, cfg)
			cfgDir := filepath.Dir(cfg)
			victim := filepath.Join(cfgDir, "stale.ts")
			body := []byte("// Code generated by problemgen 0.1.0. DO NOT EDIT.\n// source: def.yaml sha256:00\n// content\n")
			rel := "stale.ts"
			switch mode {
			case "absolute":
				rel = victim
			case "dotdot":
				victim = filepath.Join(dir, "outside.ts")
				rel = "../outside.ts"
				body = []byte("// Code generated by problemgen\n// source: a/def.yaml sha256:00\n")
			case "symlink-file":
				target := filepath.Join(cfgDir, "actual.ts")
				os.WriteFile(target, body, 0o644)
				os.Symlink(target, victim)
			case "catalog":
				rel = "stale.json"
				victim = filepath.Join(cfgDir, rel)
				body = []byte("[]")
			case "case":
				body = []byte("// Code generated by problemgen\n// source: DEF.YAML sha256:00\n")
			case "owned-dotdot":
				rel = "sub/../stale.ts"
			}
			if mode != "symlink-file" {
				os.WriteFile(victim, body, 0o644)
			}
			sum := sha256.Sum256(body)
			if mode == "edited" {
				os.WriteFile(victim, append(body, []byte("// handwritten change\n")...), 0o644)
			}
			m, _ := os.ReadFile(cfg + ".outputs")
			m = append(m, []byte(fmt.Sprintf("%x  %s\n", sum, rel))...)
			os.WriteFile(cfg+".outputs", m, 0o644)
			code, out := r3run(t, "generate", "-c", cfg)
			_, err := os.Lstat(victim)
			if mode == "owned-dotdot" {
				if !os.IsNotExist(err) {
					t.Errorf("owned contained normalized path should be removed: %d %s", code, out)
				}
				return
			}
			if err != nil {
				t.Errorf("victim removed: %d %s", code, out)
			}
			if code != 1 {
				t.Errorf("want refusal, got %d %s", code, out)
			}
			vcode, vout := r3run(t, "verify", "-c", cfg)
			if vcode != 1 || !strings.Contains(vout, "stale generated file") {
				t.Errorf("refusal forgotten: %d %s", vcode, vout)
			}
		})
	}
}

func TestR4RefusedStalePersists(t *testing.T) {
	dir := t.TempDir()
	cfg := r3Svc(t, dir, "a", "a", "{ typescript: { file: gen.ts, runtime: r }, record: { file: rec.yaml } }")
	mustGenerate(t, cfg)
	os.WriteFile(filepath.Join(dir, "a", "gen.ts"), []byte("handwritten replacement\n"), 0o644)
	r3Svc(t, dir, "a", "a", "{ record: { file: rec.yaml } }")
	code, out := r3run(t, "generate", "-c", cfg)
	if code != 1 || !strings.Contains(out, "not removing") {
		t.Fatalf("expected refusal: %d %s", code, out)
	}
	for i := 0; i < 2; i++ {
		code, out = r3run(t, "verify", "-c", cfg)
		if code != 1 || !strings.Contains(out, "stale generated file") {
			t.Errorf("verify %d forgot refused stale file: %d %s", i, code, out)
		}
	}
}

// A refused path stops the run before anything is written: no partial generate.
func TestR4RefusalWritesNothing(t *testing.T) {
	dir := t.TempDir()
	cfg := r3Svc(t, dir, "a", "a", "{ go: { file: a.go, package: p, runtime: r }, typescript: { file: out/gen.ts, runtime: r } }")
	os.MkdirAll(filepath.Join(dir, "elsewhere"), 0o755)
	os.Symlink(filepath.Join(dir, "elsewhere"), filepath.Join(dir, "a", "out"))
	code, out := r3run(t, "generate", "-c", cfg)
	if code != 2 {
		t.Fatalf("want exit 2, got %d: %s", code, out)
	}
	for _, f := range []string{"a.go", "cfg.yaml.outputs"} {
		if _, err := os.Lstat(filepath.Join(dir, "a", f)); err == nil {
			t.Errorf("%s was written although the run was refused", f)
		}
	}
	if _, err := os.Lstat(filepath.Join(dir, "elsewhere", "gen.ts")); err == nil {
		t.Errorf("wrote through the symlinked directory")
	}
}

// A hard link to an output does not make generate change the other file: the output is
// replaced by rename, never rewritten in place.
func TestR4HardLinkKeepsOtherFile(t *testing.T) {
	dir := t.TempDir()
	cfg := r3Svc(t, dir, "a", "a", "{ typescript: { file: gen.ts, runtime: r } }")
	mustGenerate(t, cfg)
	gen := filepath.Join(dir, "a", "gen.ts")
	other := filepath.Join(dir, "other.ts")
	if err := os.Link(gen, other); err != nil {
		t.Skip("no hard links here:", err)
	}
	before, _ := os.ReadFile(other)
	r3Svc(t, dir, "a", "a", "{ typescript: { file: gen.ts, runtime: other-runtime } }")
	mustGenerate(t, cfg)
	after, _ := os.ReadFile(other)
	now, _ := os.ReadFile(gen)
	if string(after) != string(before) || string(now) == string(before) {
		t.Errorf("hard-linked file changed with the output (or the output did not change)")
	}
}

// Outputs may not be (or alias) the files generation reads, nor each other.
func TestR4OutputCollisions(t *testing.T) {
	for name, tc := range map[string]struct{ outputs, want string }{
		"definition":       {"{ typescript: { file: def.yaml, runtime: r } }", "is a definition"},
		"config":           {"{ typescript: { file: cfg.yaml, runtime: r } }", "is a definition, an imported library or the config"},
		"definition-case":  {"{ typescript: { file: DEF.yaml, runtime: r } }", "is a definition"},
		"two-outputs-case": {"{ typescript: { file: gen.ts, runtime: r }, catalog: { file: GEN.ts } }", "the same file"},
		"same-output":      {"{ typescript: { file: gen.ts, runtime: r }, record: { file: ./gen.ts } }", "the same file"},
		"manifest":         {"{ typescript: { file: cfg.yaml.outputs, runtime: r } }", "the same file"},
		"directory":        {"{ typescript: { file: sub, runtime: r } }", "not a regular file"},
	} {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			cfg := r3Svc(t, dir, "a", "a", tc.outputs)
			os.MkdirAll(filepath.Join(dir, "a", "sub"), 0o755)
			defBefore, _ := os.ReadFile(filepath.Join(dir, "a", "def.yaml"))
			cfgBefore, _ := os.ReadFile(cfg)
			code, out := r3run(t, "generate", "-c", cfg)
			if code != 2 || !strings.Contains(out, tc.want) {
				t.Errorf("want exit 2 with %q, got %d: %s", tc.want, code, out)
			}
			defAfter, _ := os.ReadFile(filepath.Join(dir, "a", "def.yaml"))
			cfgAfter, _ := os.ReadFile(cfg)
			if string(defAfter) != string(defBefore) || string(cfgAfter) != string(cfgBefore) {
				t.Errorf("an input was overwritten")
			}
		})
	}
	// A hard link to the definition is the same file under another name.
	dir := t.TempDir()
	cfg := r3Svc(t, dir, "a", "a", "{ typescript: { file: gen.ts, runtime: r } }")
	if err := os.Link(filepath.Join(dir, "a", "def.yaml"), filepath.Join(dir, "a", "gen.ts")); err != nil {
		t.Skip("no hard links here:", err)
	}
	if code, out := r3run(t, "generate", "-c", cfg); code != 2 || !strings.Contains(out, "is a definition") {
		t.Errorf("hard link to the definition: want exit 2, got %d: %s", code, out)
	}
}

// The guard and the ownership check compare absolute real paths: a relative -c (the usual
// `problemgen generate` in the service directory) regenerates its own files.
func TestR4RelativeConfigPathRegenerates(t *testing.T) {
	dir := t.TempDir()
	r3Svc(t, dir, "a", "a", "{ typescript: { file: out/gen.ts, runtime: r }, record: { file: ../shared/rec.yaml } }")
	for i := 0; i < 2; i++ {
		cmd := exec.Command(os.Args[0], "-test.run=TestMainHelper", "--", "generate", "-c", "cfg.yaml")
		cmd.Env = append(os.Environ(), "PROBLEMGEN_TEST_MAIN=1")
		cmd.Dir = filepath.Join(dir, "a")
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("run %d: %v %s", i, err, out)
		}
	}
	os.WriteFile(filepath.Join(dir, "a", "def.yaml"), []byte(strings.Replace(r3Def, "detail: d", "detail: changed", 1)), 0o644)
	cmd := exec.Command(os.Args[0], "-test.run=TestMainHelper", "--", "generate", "-c", "cfg.yaml")
	cmd.Env = append(os.Environ(), "PROBLEMGEN_TEST_MAIN=1")
	cmd.Dir = filepath.Join(dir, "a")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("after a definition change: %v %s", err, out)
	}
}
