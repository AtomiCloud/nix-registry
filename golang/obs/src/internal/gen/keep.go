package gen

import (
	"strings"

	"github.com/AtomiCloud/obs/internal/contract"
)

// KeepFile is the keep-list, relative to the observability folder.
const KeepFile = "contract/keep.yaml"

// Keep is contract/keep.yaml: the names the collector may store, one per line, sorted, plain
// (no regex), as VictoriaMetrics stores them. The platform's renderer reads every
// apps/*/observability/contract/keep.yaml and turns the names into the write door's keep rule.
// The header is the contract path and hash, so `obs gen --check` finds a stale or edited file.
func Keep(c *contract.Contract) []byte {
	var b strings.Builder
	b.WriteString("# generated by obs gen from " + ContractPath(c) + "\n")
	b.WriteString("# " + HashPrefix + c.Hash + "\n")
	names := c.KeepNames()
	if len(names) == 0 {
		b.WriteString("metrics: []\n")
		return []byte(b.String())
	}
	b.WriteString("metrics:\n")
	for _, n := range names {
		b.WriteString("  - " + n + "\n")
	}
	return []byte(b.String())
}
