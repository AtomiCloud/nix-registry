package main

import (
	"fmt"
	"strings"
	"unicode/utf16"
)

func init() {
	registerLang(&Lang{Name: "csharp", File: func(o Outputs) string {
		if o.CSharp == nil {
			return ""
		}
		return o.CSharp.File
	},
		Generate: func(m *Module, c *Config, o Outputs, src string) string {
			return (&csGen{m: m, c: c, o: o.CSharp}).file(src)
		}})
}

type csGen struct {
	m *Module
	c *Config
	o *CSOut
	b strings.Builder
}

func (g *csGen) p(f string, a ...any) { fmt.Fprintf(&g.b, f, a...); g.b.WriteByte('\n') }
func (g *csGen) doc(s string) {
	if s == "" {
		return
	}
	s = strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;").Replace(s)
	g.p("/// <summary>%s</summary>", strings.NewReplacer("\n", " ", "\r", " ").Replace(s))
}
func csString(s string) string { return csUnits(utf16.Encode([]rune(s))) }
func csUnits(s []uint16) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, c := range s {
		switch c {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		default:
			if c < 32 || c >= 127 {
				fmt.Fprintf(&b, `\u%04x`, c)
			} else {
				b.WriteRune(rune(c))
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
func csType(t FieldType) string {
	switch t.Kind {
	case KString:
		return "string"
	case KInteger, KInt64:
		return "long"
	case KNumber:
		return "double"
	case KBoolean:
		return "bool"
	case KDateTime:
		return "global::System.DateTimeOffset"
	case KRef:
		return t.Ref
	case KArray:
		return "global::System.Collections.Generic.IReadOnlyList<" + csType(*t.Items) + ">"
	}
	return "object"
}
func (g *csGen) enum(t FieldType) bool { return t.Kind == KRef && g.m.TypeByName(t.Ref).IsEnum }
func (g *csGen) valueType(t FieldType) bool {
	return t.Kind == KInteger || t.Kind == KInt64 || t.Kind == KNumber || t.Kind == KBoolean || t.Kind == KDateTime || g.enum(t)
}
func (g *csGen) file(src string) string {
	g.p("// Code generated by problemgen %s. DO NOT EDIT.", toolVersion)
	g.p("// source: %s sha256:%s", src, g.m.Def.SHA256)
	g.p("// API-layer values. Domain projects must not reference this assembly.")
	g.p("#nullable enable")
	g.p("#pragma warning disable CS0618 // generated readers support deprecated contracts")
	g.p("using System;\nusing System.Collections.Generic;\nusing System.Globalization;\nusing System.Text.Json;")
	g.p("using __Rt = %s;", g.o.Runtime)
	g.p("namespace %s;", g.o.Namespace)
	g.p("public abstract partial record Problem : __Rt.ProblemValue { private protected Problem() {} private protected abstract void __Closed(); }")
	for _, nt := range g.m.Types {
		g.doc(nt.Description)
		if nt.IsEnum {
			var vs []string
			for _, v := range nt.Values {
				vs = append(vs, Pascal(v))
			}
			g.p("public enum %s { %s }", nt.Name, strings.Join(vs, ", "))
			g.p("internal static class __%sWire {", nt.Name)
			g.p(" internal static string Write(%s v) => v switch {", nt.Name)
			for _, v := range nt.Values {
				g.p("  %s.%s => %s,", nt.Name, Pascal(v), csString(v))
			}
			g.p("  _ => throw new global::System.ArgumentOutOfRangeException(nameof(v), \"invalid enum\") };")
			g.p(" internal static %s Read(global::System.Text.Json.JsonElement e) => __Rt.Decode.String(e) switch {", nt.Name)
			for _, v := range nt.Values {
				g.p("  %s => %s.%s,", csString(v), nt.Name, Pascal(v))
			}
			g.p("  _ => throw new global::System.FormatException(\"invalid enum\") };\n}")
		} else {
			g.record(nt.Name, nt.Fields, nil)
		}
	}
	for _, p := range g.m.Problems {
		g.record(Pascal(p.ID), p.Data, p)
	}
	g.p("public sealed record Unknown(__Rt.Envelope Envelope, string Reason) : Problem {")
	g.p(" private protected override void __Closed() {}")
	g.p(" public override __Rt.Meta Meta => new(\"\",Envelope.Title,Envelope.Status,false,\"\",\"\",\"\",\"\",\"\");")
	g.p(" public override string Detail() => Envelope.Detail;")
	g.p(" public override string LogLine() => __Rt.Text.Log(\"unknown problem \" + Envelope.Type + \": \" + Reason);")
	g.p(" public override bool WriteData(__Rt.Writer w) => false;\n}")
	g.p("public abstract partial record Problem {")
	g.p(" public static Problem? Parse(string body) {")
	g.p("  var e = __Rt.Decode.Envelope(body); if(e is null) return null;")
	g.p("  var a=e.Address;")
	g.p("  if(a is null || a[2]!=%s || a[3]!=%s || a[4]!=%s || a[5]!=%s) return new Unknown(e,\"foreign address\");", csString(g.c.Platform), csString(g.c.Service), csString(g.m.Def.Module), csString(g.m.Def.Version))
	g.p("  try { return a[6] switch {")
	for _, p := range g.m.Problems {
		g.p("   %s when e.Status == %d => %s.__Read(e),", csString(p.ID), p.Status, Pascal(p.ID))
	}
	g.p("   _ => new Unknown(e,\"unknown id or mismatched status\") };")
	g.p("  } catch(global::System.Exception ex) when(ex is global::System.FormatException or global::System.Text.Json.JsonException or global::System.InvalidOperationException or global::System.OverflowException or global::System.ArgumentException) { return new Unknown(e, ex.Message); }")
	g.p(" }\n}")
	return g.b.String()
}
func (g *csGen) record(n string, fs []*Field, p *Problem) {
	if p != nil {
		g.doc(p.Title + ". " + p.Description + " Detail: " + p.DetailSrc)
	}
	if p != nil && p.Deprecated != "" {
		g.p("[global::System.Obsolete(%s)]", csString(p.Deprecated))
	}
	base := ""
	if p != nil {
		base = " : Problem"
	}
	g.p("public sealed record %s%s {", n, base)
	if p != nil {
		g.p(" private protected override void __Closed() {}")
	}
	for _, f := range fs {
		typ := csType(f.Type)
		if f.Optional {
			typ += "?"
		}
		if f.Private {
			g.p(" private %s %s { get; init; }", typ, Pascal(f.Name))
			continue
		}
		g.doc(f.Description)
		if f.Deprecated != "" {
			g.p(" [global::System.Obsolete(%s)]", csString(f.Deprecated))
		}
		g.p(" public %s %s { get; init; }", typ, Pascal(f.Name))
	}
	// Required fields are positional parameters. Optional public fields are set with init
	// (object initialiser). Optional private fields have no public setter, so they are
	// trailing optional parameters: the only way to supply them.
	var args []string
	for _, f := range fs {
		if !f.Optional {
			args = append(args, csType(f.Type)+" "+f.Name)
		}
	}
	for _, f := range fs {
		if f.Optional && f.Private {
			args = append(args, csType(f.Type)+"? "+f.Name+" = null")
		}
	}
	g.p(" public %s(%s) {", n, strings.Join(args, ", "))
	for _, f := range fs {
		if !f.Optional || f.Private {
			g.p("  %s = %s;", Pascal(f.Name), f.Name)
		}
	}
	g.p(" }")
	if p != nil {
		g.p(" private static readonly __Rt.Meta metadata = new(%s,%s,%d,%v,%s,%s,%s,%s,%s);", csString(p.ID), csString(p.Title), p.Status, p.Recoverable, csString(g.c.Platform), csString(g.c.Service), csString(g.m.Def.Module), csString(g.m.Def.Version), csString(g.c.Portal))
		g.p(" public override __Rt.Meta Meta => metadata;")
		if p.RetryAfter != "" {
			g.p(" public override long? RetryAfterSeconds => %s;", Pascal(p.RetryAfter))
		}
		g.p(" public override string Detail() => ReceivedDetail ?? %s;", g.template(p, p.Detail, false))
		g.p(" public override string LogLine() => %s;", g.template(p, p.Log, true))
		g.p(" public override bool WriteData(__Rt.Writer w) {")
		if len(p.PublicData()) == 0 {
			g.p("  return false;")
		} else {
			g.writeFields(fs)
			g.p("  return true;")
		}
		g.p(" }")
		g.p(" internal static %s __Read(__Rt.Envelope e) {", n)
		if len(p.PublicData()) > 0 {
			g.p("  var d=__Rt.Decode.Object(e.Data);")
		}
	} else {
		g.p(" internal void __Write(__Rt.Writer w) {")
		g.writeFields(fs)
		g.p(" }")
		g.p(" internal static %s __Read(global::System.Text.Json.JsonElement raw) {", n)
		g.p("  var d=__Rt.Decode.Object(raw);")
	}
	var vals, opts []string
	for _, f := range fs {
		if f.Private {
			if !f.Optional {
				zero := "default(" + csType(f.Type) + ")!"
				if f.Type.Kind == KString {
					zero = "\"\""
				}
				if f.Type.Kind == KArray {
					zero = "global::System.Array.Empty<" + csType(*f.Type.Items) + ">()"
				}
				vals = append(vals, zero)
			}
			continue
		}
		raw := "__Rt.Decode.Required(d," + csString(f.Name) + ")"
		if f.Optional {
			opts = append(opts, Pascal(f.Name)+" = __Rt.Decode.Optional(d,"+csString(f.Name)+") is global::System.Text.Json.JsonElement "+f.Name+"Value ? "+g.decode(f.Type, f.Name+"Value")+" : null")
		} else {
			vals = append(vals, g.decode(f.Type, raw))
		}
	}
	if p != nil {
		opts = append(opts, "Instance = e.Instance", "ReceivedType = e.Type", "ReceivedDetail = e.Detail")
	}
	suffix := ""
	if len(opts) > 0 {
		suffix = " { " + strings.Join(opts, ", ") + " }"
	}
	g.p("  return new %s(%s)%s;", n, strings.Join(vals, ", "), suffix)
	g.p(" }\n}")
}
func (g *csGen) writeFields(fs []*Field) {
	g.p("  w.BeginObject();")
	for _, f := range fs {
		if f.Private {
			continue
		}
		expr := Pascal(f.Name)
		if f.Optional {
			g.p("  if(%s is not null) {", expr)
			if g.valueType(f.Type) {
				expr += ".Value"
			}
		}
		g.p("  w.Key(%s);", csString(f.Name))
		g.writeValue(f.Type, expr)
		if f.Optional {
			g.p("  }")
		}
	}
	g.p("  w.EndObject();")
}
func (g *csGen) writeValue(t FieldType, e string) {
	switch t.Kind {
	case KString:
		g.p("  w.String(%s);", e)
	case KInteger:
		g.p("  w.Integer(%s);", e)
	case KInt64:
		g.p("  w.Int64(%s);", e)
	case KNumber:
		g.p("  w.Number(%s);", e)
	case KBoolean:
		g.p("  w.Bool(%s);", e)
	case KDateTime:
		g.p("  w.DateTime(%s);", e)
	case KArray:
		g.p("  w.BeginArray(); foreach(var item in %s) {", e)
		g.writeValue(*t.Items, "item")
		g.p("  } w.EndArray();")
	case KRef:
		if g.enum(t) {
			g.p("  w.String(__%sWire.Write(%s));", t.Ref, e)
		} else {
			g.p("  %s.__Write(w);", e)
		}
	}
}
func (g *csGen) decode(t FieldType, e string) string {
	switch t.Kind {
	case KString:
		return "__Rt.Decode.String(" + e + ")"
	case KInteger:
		return "__Rt.Decode.Integer(" + e + ")"
	case KInt64:
		return "__Rt.Decode.Int64(" + e + ")"
	case KNumber:
		return "__Rt.Decode.Number(" + e + ")"
	case KBoolean:
		return "__Rt.Decode.Bool(" + e + ")"
	case KDateTime:
		return "__Rt.Decode.DateTime(" + e + ")"
	case KRef:
		if g.enum(t) {
			return "__" + t.Ref + "Wire.Read(" + e + ")"
		}
		return t.Ref + ".__Read(" + e + ")"
	case KArray:
		return "__Rt.Decode.Array(" + e + ", item => " + g.decode(*t.Items, "item") + ")"
	}
	return ""
}
func (g *csGen) template(p *Problem, t *Template, log bool) string {
	var parts []string
	for _, part := range t.Parts {
		if !part.IsPlaceholder() {
			parts = append(parts, csString(part.Lit))
			continue
		}
		f := p.Field(part.Field)
		x := Pascal(f.Name)
		var expr string
		value := x
		if f.Optional && g.valueType(f.Type) {
			value += ".Value"
		}
		switch {
		case part.Count:
			expr = value + ".Count.ToString(global::System.Globalization.CultureInfo.InvariantCulture)"
		case f.Type.Kind == KString:
			expr = value
		case f.Type.Kind == KInteger || f.Type.Kind == KInt64:
			expr = value + ".ToString(global::System.Globalization.CultureInfo.InvariantCulture)"
		case f.Type.Kind == KNumber:
			expr = "__Rt.Text.Number(" + value + ")"
		case f.Type.Kind == KBoolean:
			expr = "(" + value + " ? \"true\" : \"false\")"
		case f.Type.Kind == KDateTime:
			expr = "__Rt.Text.DateTime(" + value + ")"
		case g.enum(f.Type):
			expr = "__" + f.Type.Ref + "Wire.Write(" + value + ")"
		}
		wrap := "Detail"
		if log {
			wrap = "Log"
		}
		expr = "__Rt.Text." + wrap + "(" + expr + ")"
		if f.Optional {
			expr = "(" + x + " is null ? " + csString(part.Default) + " : " + expr + ")"
		}
		parts = append(parts, expr)
	}
	if len(parts) == 0 {
		return "\"\""
	}
	return "string.Concat(" + strings.Join(parts, ", ") + ")"
}
