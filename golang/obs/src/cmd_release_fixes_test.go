func TestReleaseAllContractSymlinks(t *testing.T) {
	for _, kind := range []string{"inside", "dangling", "outside", "loop"} {
		t.Run(kind, func(t *testing.T) {
			root := repo(t, map[string]string{"observability/base/contract.yaml": "service: base\n", "observability/base/seed.yaml": releaseSeed, "observability/link/seed.yaml": releaseSeed})
			t.Chdir(root)
			gen2Write(t, root, "sources/link.yaml", "service: link\n")
			file := filepath.Join(root, "observability/link/contract.yaml")
			target := filepath.Join(root, "sources/link.yaml")
			if kind == "dangling" {
				target = filepath.Join(root, "missing.yaml")
			}
			if kind == "outside" {
				target = filepath.Join(t.TempDir(), "external.yaml")
				if err := os.WriteFile(target, []byte("service: external\n"), 0644); err != nil {
					t.Fatal(err)
				}
			}
			if kind == "loop" {
				target = file
			}
			if err := os.Symlink(target, file); err != nil {
				t.Fatal(err)
			}
			for _, cmd := range []string{"gen", "check", "test"} {
				rc, out := obs(cmd, "--all")
				if kind == "inside" {
					if rc != 0 || !strings.Contains(out, "observability/link/contract.yaml") {
						t.Errorf("%s inside symlink skipped: rc=%d %s", cmd, rc, out)
					}
				} else if rc != 2 || !strings.Contains(out, "observability/link/contract.yaml") {
					t.Errorf("%s invalid symlink must be input error: rc=%d %s", cmd, rc, out)
				}
			}
		})
	}
}

