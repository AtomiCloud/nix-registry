#!/usr/bin/env bash
# One contract shape: source: entries, estimate labels, follows, used_by, several contracts in one
# repository, and the collector keep-list (contract/keep.yaml). Every check is a green baseline
# and a planted failure that is red and names the file, the rule and the bad token.
#   contract-source.sh <obs binary>
set -euo pipefail
OBS=$1
here="$(cd "$(dirname "$0")" && pwd)"
fx="$here/fixtures"
work="$(mktemp -d)"
trap 'rm -rf "${work:?}"' EXIT
run() {
  set +e
  "$OBS" "$@" >"$work/out" 2>&1
  rc=$?
  set -e
}
expect() {
  local want=$1
  shift
  if [ "$rc" -ne "$want" ]; then
    cat "$work/out"
    echo "contract-source: exit $rc wanted $want"
    exit 1
  fi
  for token in "$@"; do
    if ! grep -qF -- "$token" "$work/out"; then
      cat "$work/out"
      echo "contract-source: missing $token"
      exit 1
    fi
  done
}
absent() {
  if grep -qF -- "$1" "$work/out"; then
    cat "$work/out"
    echo "contract-source: must be absent: $1"
    exit 1
  fi
}
cluster="$fx/gen/ok-source-cluster/observability"

# ---- green baseline: the cluster contract of the platform draft -------------------------
run check --dir "$cluster"
expect 0 'obs check: ok: 32 metrics' 'metric kube_pod_info (gauge): worst case 110 series (estimate max), budget 110; source kube-state-metrics; used by' 'metric kube_pod_status_phase (gauge): worst case 550 series (estimate max), budget 550'
absent 'pod label dropped'
echo "PASS contract-source: the cluster contract checks green: estimate max, follows adds no series, source and used_by printed"

# ---- gen: no types for a source: entry, a keep line for each ------------------------------
rm -rf "${work:?}/gen1"
mkdir -p "$work/gen1/observability"
cp "$cluster/contract.yaml" "$work/gen1/observability/"
run gen --dir "$work/gen1/observability"
expect 0 'wrote observability/contract/keep.yaml'
diff -r "$cluster/contract" "$work/gen1/observability/contract" >/dev/null || {
  diff -r "$cluster/contract" "$work/gen1/observability/contract" || true
  echo "contract-source: a fresh generate differs from the committed keep.yaml, events.json and aggregation.yaml"
  exit 1
}
grep -qx '  - kube_pod_status_phase' "$work/gen1/observability/contract/keep.yaml"
grep -qx '  - container_cpu_usage_seconds_total' "$work/gen1/observability/contract/keep.yaml"
[ "$(sed -n '1p' "$work/gen1/observability/contract/keep.yaml")" = '# generated by obs gen from observability/contract.yaml' ]
sed -n '2p' "$work/gen1/observability/contract/keep.yaml" | grep -Eq '^# contract-hash: sha256:[0-9a-f]{64}$'
[ "$(sed -n '3p' "$work/gen1/observability/contract/keep.yaml")" = 'metrics:' ]
if grep -Eq '[^a-z0-9_ :#/.-]|\*|\|' "$work/gen1/observability/contract/keep.yaml"; then
  echo "contract-source: keep.yaml holds a character that is not a plain name"
  exit 1
fi
sort -c <(sed -n 's/^  - //p' "$work/gen1/observability/contract/keep.yaml")
echo "PASS contract-source: obs gen writes contract/keep.yaml in the platform format (header, hash, sorted plain names), equal to the golden file"

# a contract with generate targets gets no type for the source: entry
rm -rf "${work:?}/gen2"
mkdir -p "$work/gen2/observability"
cat >"$work/gen2/observability/contract.yaml" <<'YAML'
service: mixed
generate:
  - { lang: go, out: gen/go }
types:
  pod: { kind: estimate, min: 1, max: 9, churn_per_day: 1 }
  lane: { kind: enum, values: [a, b] }
metrics:
  mixed.jobs:
    kind: counter
    budget: 2
    labels: { lane: lane }
  kube_pod_info:
    source: kube-state-metrics
    kind: gauge
    budget: 9
    used_by: [hub/dash/pods]
    labels:
      pod: pod
      uid: { follows: pod }
YAML
run gen --dir "$work/gen2/observability"
expect 0
grep -q 'mixed.jobs' "$work/gen2/gen/go/signals.go"
if grep -riq 'kube_pod_info\|KubePodInfo' "$work/gen2/gen"; then
  grep -ri 'kube_pod_info\|KubePodInfo' "$work/gen2/gen" || true
  echo "contract-source: generated code names the source entry"
  exit 1
fi
grep -qx '  - kube_pod_info' "$work/gen2/observability/contract/keep.yaml"
grep -qx '  - mixed_jobs_total' "$work/gen2/observability/contract/keep.yaml"
run gen --check --dir "$work/gen2/observability"
expect 0 'obs gen --check: ok'
echo "PASS contract-source: obs gen makes no types for a source: entry, keeps its name and our own, and gen --check is green"

# ---- gen --check: a missing, edited or stale keep.yaml is red -----------------------------
rm -rf "${work:?}/k1"
cp -r "$fx/gen/ok-source-cluster" "$work/k1"
chmod -R u+w "$work/k1"
run gen --check --dir "$work/k1/observability"
expect 0 'obs gen --check: ok'
rm "$work/k1/observability/contract/keep.yaml"
run gen --check --dir "$work/k1/observability"
expect 1 'contract/keep.yaml: [gen-missing]'
echo "PASS contract-source: gen --check names a missing keep.yaml ([gen-missing])"
cp "$fx/gen/ok-source-cluster/observability/contract/keep.yaml" "$work/k1/observability/contract/keep.yaml"
chmod u+w "$work/k1/observability/contract/keep.yaml"
sed -i 's/^  - kube_pod_info$/  - kube_pod_info\n  - sneaked_in_by_hand/' "$work/k1/observability/contract/keep.yaml"
run gen --check --dir "$work/k1/observability"
expect 1 'contract/keep.yaml: [gen-edited]' 'sneaked_in_by_hand'
echo "PASS contract-source: gen --check names a hand-edited keep.yaml ([gen-edited]) and the line"
cp "$fx/gen/ok-source-cluster/observability/contract/keep.yaml" "$work/k1/observability/contract/keep.yaml"
sed -i 's/min: 28, max: 110/min: 29, max: 110/' "$work/k1/observability/contract.yaml"
run gen --check --dir "$work/k1/observability"
expect 1 'contract/keep.yaml: [gen-stale]' 'contract/events.json: [gen-stale]'
echo "PASS contract-source: gen --check names a stale keep.yaml after a contract change ([gen-stale])"

# ---- planted failures: estimate, follows, over budget, used_by ----------------------------
plant() { # plant <name> <sed expression on the cluster contract>
  rm -rf "${work:?}/$1"
  mkdir -p "$work/$1/observability"
  sed "$2" "$cluster/contract.yaml" >"$work/$1/observability/contract.yaml"
}
# an estimate label on an entry that has no source: names file:line
rm -rf "${work:?}/own"
mkdir -p "$work/own/observability"
cat >"$work/own/observability/contract.yaml" <<'YAML'
service: own
types:
  pod: { kind: estimate, min: 1, max: 5, churn_per_day: 0 }
metrics:
  own.things:
    kind: counter
    budget: 5
    labels:
      pod: pod
YAML
run check --dir "$work/own/observability"
expect 1 "FAIL $work/own/observability/contract.yaml metrics.own.things.labels.pod: [estimate-not-source]" "observability/contract.yaml:9:" 'label "pod"'
echo "PASS contract-source: an estimate on an entry with no source is red and names file:line, the metric and the label"
# follows a label that is not there
plant f1 's/uid: { follows: pod }/uid: { follows: podd }/'
run check --dir "$work/f1/observability"
expect 1 '[follows]' '"podd"' "observability/contract.yaml:"
echo "PASS contract-source: follows a missing label is red and names the label"
# over budget uses the estimate max
plant b1 's/^    budget: 110$/    budget: 109/'
run check --dir "$work/b1/observability"
expect 1 '[over-budget]' 'worst case is 110 series, over its budget of 109'
echo "PASS contract-source: a budget under the estimate max is red"
# unknown key under a label
plant u1 's/uid: { follows: pod }/uid: { follow: pod }/'
run check --dir "$work/u1/observability"
expect 2 'follow'
echo "PASS contract-source: a misspelt follows key is an input error naming the key"
# a source entry that does not say who uses it is a warning, not a failure
rm -rf "${work:?}/w1"
mkdir -p "$work/w1/observability"
cat >"$work/w1/observability/contract.yaml" <<'YAML'
service: w
metrics:
  kube_node_info:
    source: kube-state-metrics
    kind: gauge
YAML
run check --dir "$work/w1/observability"
expect 0 "WARN $work/w1/observability/contract.yaml metrics.kube_node_info: [used-by-missing]" 'obs check: ok'
echo "PASS contract-source: a source entry with no used_by is a warning (exit 0) that names the entry"

# ---- several contracts in one repository ---------------------------------------------------
rm -rf "${work:?}/repo"
mkdir -p "$work/repo/.git" "$work/repo/apps/cluster" "$work/repo/apps/hub/observability/dashboards"
cp -r "$cluster" "$work/repo/apps/cluster/observability"
chmod -R u+w "$work/repo"
cat >"$work/repo/apps/hub/observability/contract.yaml" <<'YAML'
service: hub
types:
  lane: { kind: enum, values: [a, b] }
metrics:
  hub.jobs:
    kind: counter
    budget: 2
    labels: { lane: lane }
YAML
cat >"$work/repo/apps/hub/observability/dashboards/pods.json" <<'JSON'
{"title":"pods","schemaVersion":42,"panels":[{"id":1,"title":"phase","type":"timeseries","datasource":{"type":"prometheus","uid":"vm"},"targets":[{"refId":"A","expr":"sum by (phase) (kube_pod_status_phase{phase=\"Running\"})"}]}]}
JSON
run check --dir "$work/repo/apps/hub/observability"
expect 0 'metric hub.jobs (counter)' 'metric kube_pod_status_phase (gauge)' 'contract apps/cluster/observability/contract.yaml'
echo "PASS contract-source: obs check reads every contract.yaml of the repository and prints each"
run check --dir "$work/repo/apps/hub/observability" --contracts none
expect 0 'metric hub.jobs (counter)'
absent 'kube_pod_status_phase'
echo "PASS contract-source: --contracts none reads this folder's contract only"
run query --static --dir "$work/repo/apps/hub/observability"
expect 0 'obs query --static: ok'
run query --static --dir "$work/repo/apps/hub/observability" --contracts none
expect 1 'kube_pod_status_phase'
echo "PASS contract-source: a dashboard may read another contract's metric; with --contracts none the same metric is red"
# a name both declare
sed -i 's/hub.jobs/kube_pod_status_phase/; s/kind: counter/kind: gauge\n    across_pods: max/' "$work/repo/apps/hub/observability/contract.yaml"
run check --dir "$work/repo/apps/hub/observability"
expect 1 '[metric-clash]' 'apps/hub/observability/contract.yaml' 'apps/cluster/observability/contract.yaml' 'kube_pod_status_phase'
run query --static --dir "$work/repo/apps/hub/observability"
expect 1 '[metric-clash]' 'apps/cluster/observability/contract.yaml'
echo "PASS contract-source: a stored name two contracts declare is red and names both files"
absent "$work/repo/apps/cluster"
echo "PASS contract-source: the clash message names files relative to the Git root, never an absolute path (the other contract)"
# a platform metric listed by both contracts is shared, not a clash
cat >"$work/repo/apps/hub/observability/contract.yaml" <<'YAML'
service: hub
platform_metrics:
  http.server.request.duration: [http.route]
YAML
printf '\nplatform_metrics:\n  http.server.request.duration: [http.request.method]\n' >>"$work/repo/apps/cluster/observability/contract.yaml"
run check --dir "$work/repo/apps/hub/observability"
expect 0 'obs check: ok'
absent '[metric-clash]'
echo "PASS contract-source: a platform metric two contracts list is shared, not a clash"
# a platform metric against a source: entry of another contract (a stored name both would write)
cat >"$work/repo/apps/hub/observability/contract.yaml" <<'YAML'
service: hub
platform_metrics:
  kube.pod.status.phase: [phase]
YAML
run check --dir "$work/repo/apps/hub/observability"
expect 1 '[metric-clash]' 'apps/hub/observability/contract.yaml' 'apps/cluster/observability/contract.yaml' 'kube_pod_status_phase'
absent "$work/repo/apps/cluster"
echo "PASS contract-source: a platform metric against another contract's source: entry is red and names both files"
