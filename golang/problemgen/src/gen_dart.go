package main

import (
	"fmt"
	"strings"
	"unicode/utf16"
)

func init() {
	registerLang(&Lang{
		Name: "dart",
		File: func(o Outputs) string {
			if o.Dart == nil {
				return ""
			}
			return o.Dart.File
		},
		Generate: func(m *Module, cfg *Config, o Outputs, src string) string {
			return GenerateDart(m, cfg, o.Dart, src)
		},
	})
}

// GenerateDart renders the Dart output for one module: a sealed class hierarchy
// (`Problem` + one `final class` per problem + `Unknown`), named-parameter constructors,
// the serialiser and the parser. None of it extends Exception or Error.
func GenerateDart(m *Module, cfg *Config, o *DartOut, source string) string {
	g := &dartGen{m: m, cfg: cfg, o: o}
	return g.file(source)
}

type dartGen struct {
	m   *Module
	cfg *Config
	o   *DartOut
	b   strings.Builder
}

func (g *dartGen) p(f string, a ...any) { fmt.Fprintf(&g.b, f, a...); g.b.WriteByte('\n') }

// ---- Dart source literals ----

// dartEsc escapes a Go string for the inside of a single-quoted Dart literal: `\`, `'`, `$`
// and everything that is not printable ASCII (as \u{X}), so the generated file is pure ASCII.
func dartEsc(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\'':
			b.WriteString(`\'`)
		case r == '$':
			b.WriteString(`\$`)
		case r >= 0x20 && r < 0x7f:
			b.WriteRune(r)
		default:
			fmt.Fprintf(&b, `\u{%X}`, r)
		}
	}
	return b.String()
}

func dartStr(s string) string { return "'" + dartEsc(s) + "'" }

// dartStrUnits renders UTF-16 code units (lone surrogates survive) as a Dart literal.
func dartStrUnits(u []uint16) string {
	var b strings.Builder
	b.WriteByte('\'')
	for i := 0; i < len(u); i++ {
		c := u[i]
		switch {
		case c == '\\':
			b.WriteString(`\\`)
		case c == '\'':
			b.WriteString(`\'`)
		case c == '$':
			b.WriteString(`\$`)
		case c >= 0x20 && c < 0x7f:
			b.WriteByte(byte(c))
		case utf16.IsSurrogate(rune(c)) && c < 0xdc00 && i+1 < len(u) && u[i+1] >= 0xdc00 && u[i+1] < 0xe000:
			fmt.Fprintf(&b, `\u{%X}`, utf16.DecodeRune(rune(c), rune(u[i+1])))
			i++
		default:
			fmt.Fprintf(&b, `\u%04X`, c)
		}
	}
	b.WriteByte('\'')
	return b.String()
}

// dartDoc flattens text for a /// comment. "{@" starts a Dart doc directive
// ({@template}, {@macro}, ...); an unknown one is an analyzer warning, so the
// "@" is written as an HTML entity (dartdoc renders it as "@").
func dartDoc(s string) string {
	return strings.NewReplacer("\r", " ", "\n", " ", "{@", "{&#64;").Replace(s)
}

// dartEnumBad are enum constant names Dart does not allow (or that would shadow members).
var dartEnumBad = setOf("values", "index", "hashCode", "runtimeType", "toString", "noSuchMethod", "name", "wire")

// dartEnumConst is the Dart constant name of an enum wire value.
func dartEnumConst(v string) string {
	c := Camel(v)
	if dartEnumBad[c] || reservedFieldNames[c] {
		return c + "_"
	}
	return c
}

func (g *dartGen) isEnum(t FieldType) bool {
	if t.Kind != KRef {
		return false
	}
	nt := g.m.TypeByName(t.Ref)
	return nt != nil && nt.IsEnum
}

func (g *dartGen) dartType(t FieldType) string {
	switch t.Kind {
	case KString:
		return "String"
	case KInteger, KInt64:
		return "int"
	case KNumber:
		return "double"
	case KBoolean:
		return "bool"
	case KDateTime:
		return "DateTime"
	case KArray:
		return "List<" + g.dartType(*t.Items) + ">"
	case KRef:
		return t.Ref
	}
	return "Object"
}

func (g *dartGen) file(source string) string {
	g.p("// Code generated by problemgen %s. DO NOT EDIT.", toolVersion)
	g.p("// source: %s sha256:%s", source, g.m.Def.SHA256)
	g.p("//")
	g.p("// Problems of %s/%s module %s, version %s.", g.cfg.Platform, g.cfg.Service, g.m.Def.Module, g.m.Def.Version)
	g.p("// These are API-layer values: none of them is an Exception or Error, and domain")
	g.p("// packages must not import this library (enforced by the package graph).")
	g.p("//")
	g.p("// dart format off")
	g.p("// ignore_for_file: type=lint, deprecated_member_use_from_same_package")
	g.p("")
	g.p("import '%s' as rt;", g.o.Runtime)
	g.p("")
	g.p("/// The closed set of problems of this module, plus [Unknown] for anything else a client")
	g.p("/// receives. A switch over it without a default is checked for exhaustiveness. It is not")
	g.p("/// an Exception or Error and is never thrown.")
	g.p("sealed class Problem implements rt.Problem {")
	g.p("  Problem._(this.instance, this.cause, this._received);")
	g.p("")
	g.p("  @override")
	g.p("  final String? instance;")
	g.p("")
	g.p("  @override")
	g.p("  final Object? cause;")
	g.p("")
	g.p("  final rt.Received? _received;")
	g.p("")
	g.p("  @override")
	g.p("  String? get receivedType => _received?.type;")
	g.p("")
	g.parseFn()
	g.p("}")
	g.p("")
	reach := publicReach(g.m)
	for _, t := range g.m.Types {
		g.namedType(t, reach[t.Name])
	}
	for _, p := range g.m.Problems {
		g.problem(p)
	}
	g.unknown()
	return g.b.String()
}

// ---- named types ----

// namedType emits the type, and its wire helpers only when a public field reaches it: a type
// used only by private fields is never written or decoded, and an unused private helper is
// an analyzer warning (unused_element) in the consuming project.
func (g *dartGen) namedType(t *NamedType, wire bool) {
	if t.IsEnum {
		doc := t.Name
		if t.Description != "" {
			doc += ": " + dartDoc(t.Description)
		}
		g.p("/// %s", doc)
		g.p("enum %s {", t.Name)
		for i, v := range t.Values {
			end := ","
			if i == len(t.Values)-1 {
				end = ";"
			}
			g.p("  %s(%s)%s", dartEnumConst(v), dartStr(v), end)
		}
		g.p("")
		g.p("  const %s(this.wire);", t.Name)
		g.p("")
		g.p("  /// The wire value.")
		g.p("  final String wire;")
		g.p("}")
		g.p("")
		if !wire {
			return
		}
		g.p("%s _decode%s(Object? r) {", t.Name, t.Name)
		g.p("  final s = rt.decodeString(r);")
		g.p("  for (final v in %s.values) {", t.Name)
		g.p("    if (v.wire == s) return v;")
		g.p("  }")
		g.p("  throw FormatException('%s: \"$s\" is not a declared value');", t.Name)
		g.p("}")
		g.p("")
		return
	}
	doc := t.Name
	if t.Description != "" {
		doc += ": " + dartDoc(t.Description)
	}
	g.p("/// %s", doc)
	g.p("final class %s {", t.Name)
	g.p("  const %s({", t.Name)
	for _, f := range t.Fields {
		if f.Optional {
			g.p("    this.%s,", f.Name)
		} else {
			g.p("    required this.%s,", f.Name)
		}
	}
	g.p("  });")
	g.p("")
	for _, f := range t.Fields {
		g.fieldDecl(f, "  ", false)
	}
	g.p("}")
	g.p("")
	if !wire {
		return
	}
	g.p("void _write%s(rt.Writer w, %s v) {", t.Name, t.Name)
	g.p("  w.beginObject();")
	n := 0
	for _, f := range t.Fields {
		g.writeField(f, "v.", "  ", &n)
	}
	g.p("  w.endObject();")
	g.p("}")
	g.p("")
	g.p("%s _decode%s(Object? r) {", t.Name, t.Name)
	g.p("  final m = rt.asObject(r);")
	g.p("  return %s(", t.Name)
	for _, f := range t.Fields {
		g.p("    %s: %s,", f.Name, g.decodeField(f))
	}
	g.p("  );")
	g.p("}")
	g.p("")
}

func (g *dartGen) fieldDecl(f *Field, indent string, private bool) {
	// A private field's description and deprecation note are definition metadata that never
	// leave the server; they are not copied into generated source either.
	desc := f.Description
	if desc != "" && !private {
		g.p("%s/// %s", indent, dartDoc(desc))
	}
	if f.Deprecated != "" && !private {
		g.p("%s@Deprecated(%s)", indent, dartStr(f.Deprecated))
	}
	ty := g.dartType(f.Type)
	switch {
	case private:
		g.p("%s/// Private: log only, never on the wire.", indent)
		g.p("%sfinal %s? _%s;", indent, ty, f.Name)
	case f.Optional:
		g.p("%sfinal %s? %s;", indent, ty, f.Name)
	default:
		g.p("%sfinal %s %s;", indent, ty, f.Name)
	}
	g.p("")
}

// decoderExpr is a Dart expression of type `T Function(Object?)` decoding a value of type t.
func (g *dartGen) decoderExpr(t FieldType) string {
	switch t.Kind {
	case KString:
		return "rt.decodeString"
	case KInteger:
		return "rt.decodeInteger"
	case KInt64:
		return "rt.decodeInt64"
	case KNumber:
		return "rt.decodeNumber"
	case KBoolean:
		return "rt.decodeBool"
	case KDateTime:
		return "rt.decodeDateTime"
	case KArray:
		return "rt.listOf(" + g.decoderExpr(*t.Items) + ")"
	case KRef:
		return "_decode" + t.Ref
	}
	return "rt.decodeString"
}

func (g *dartGen) decodeField(f *Field) string {
	fn := "req"
	if f.Optional {
		fn = "opt"
	}
	return fmt.Sprintf("rt.%s(m, %s, %s)", fn, dartStr(f.Name), g.decoderExpr(f.Type))
}

// writeValue emits statements writing expr (of type t) as one JSON value.
func (g *dartGen) writeValue(expr string, t FieldType, indent string) {
	switch t.Kind {
	case KString:
		g.p("%sw.string(%s);", indent, expr)
	case KInteger:
		g.p("%sw.integer(%s);", indent, expr)
	case KInt64:
		g.p("%sw.int64(%s);", indent, expr)
	case KNumber:
		g.p("%sw.number(%s);", indent, expr)
	case KBoolean:
		g.p("%sw.boolean(%s);", indent, expr)
	case KDateTime:
		g.p("%sw.dateTime(%s);", indent, expr)
	case KArray:
		g.p("%sw.beginArray();", indent)
		g.p("%sfor (final e in %s) {", indent, expr)
		g.writeValue("e", *t.Items, indent+"  ")
		g.p("%s}", indent)
		g.p("%sw.endArray();", indent)
	case KRef:
		if g.isEnum(t) {
			g.p("%sw.string(%s.wire);", indent, expr)
		} else {
			g.p("%s_write%s(w, %s);", indent, t.Ref, expr)
		}
	}
}

// writeField emits the write of one public field; recv is "this." or "v.".
func (g *dartGen) writeField(f *Field, recv, indent string, n *int) {
	if f.Private {
		return
	}
	if f.Optional {
		*n++
		v := fmt.Sprintf("o%d", *n)
		g.p("%sfinal %s = %s%s;", indent, v, recv, f.Name)
		g.p("%sif (%s != null) {", indent, v)
		g.p("%s  w.key(%s);", indent, dartStr(f.Name))
		g.writeValue(v, f.Type, indent+"  ")
		g.p("%s}", indent)
		return
	}
	g.p("%sw.key(%s);", indent, dartStr(f.Name))
	g.writeValue(recv+f.Name, f.Type, indent)
}

// ---- templates ----

func (g *dartGen) tplValue(f *Field, part Part, x string, forLog bool) string {
	if part.Count {
		return x + ".length.toString()"
	}
	switch {
	case f.Type.Kind == KString:
		if forLog {
			return "rt.logValue(" + x + ")"
		}
		return "rt.detailValue(" + x + ")"
	case f.Type.Kind == KInteger || f.Type.Kind == KInt64 || f.Type.Kind == KBoolean:
		return x + ".toString()"
	case f.Type.Kind == KNumber:
		return "rt.templateNumber(" + x + ")"
	case f.Type.Kind == KDateTime:
		return "rt.formatDateTime(" + x + ")"
	case g.isEnum(f.Type):
		return x + ".wire"
	}
	return x + ".toString()"
}

// renderTemplate returns a Dart string literal (with interpolations) for the template.
func (g *dartGen) renderTemplate(p *Problem, t *Template, forLog bool) string {
	var b strings.Builder
	b.WriteByte('\'')
	for _, part := range t.Parts {
		if !part.IsPlaceholder() {
			b.WriteString(dartEsc(part.Lit))
			continue
		}
		f := p.Field(part.Field)
		ref := "this." + f.Name
		if f.Private {
			ref = "this._" + f.Name
		}
		switch {
		case f.Private && !f.Optional:
			// a received problem has no private data
			fmt.Fprintf(&b, "${switch (%s) { null => rt.notReceived, final v => %s }}", ref, g.tplValue(f, part, "v", forLog))
		case f.Optional:
			fmt.Fprintf(&b, "${switch (%s) { null => %s, final v => %s }}", ref, dartStr(part.Default), g.tplValue(f, part, "v", forLog))
		default:
			fmt.Fprintf(&b, "${%s}", strings.TrimSuffix(g.tplValue(f, part, ref, forLog), ".toString()"))
		}
	}
	b.WriteByte('\'')
	return b.String()
}

// ---- problems ----

func (g *dartGen) problem(p *Problem) {
	n := Pascal(p.ID)
	g.p("/// `%s` (%d): %s", p.ID, p.Status, dartDoc(p.Title))
	if p.Description != "" {
		g.p("///")
		g.p("/// %s", dartDoc(p.Description))
	}
	g.p("///")
	g.p("/// detail: `%s`", dartDoc(p.DetailSrc))
	if p.Deprecated != "" {
		g.p("@Deprecated(%s)", dartStr(p.Deprecated))
	}
	g.p("final class %s extends Problem {", n)

	// public constructor: required fields are required named parameters
	g.p("  %s({", n)
	for _, f := range p.Data {
		switch {
		case f.Private && f.Optional:
			g.p("    %s? %s,", g.dartType(f.Type), f.Name)
		case f.Private:
			g.p("    required %s %s,", g.dartType(f.Type), f.Name)
		case f.Optional:
			g.p("    this.%s,", f.Name)
		default:
			g.p("    required this.%s,", f.Name)
		}
	}
	g.p("    String? instance,")
	g.p("    Object? cause,")
	g.p("  })")
	var inits []string
	for _, f := range p.Data {
		if f.Private {
			inits = append(inits, fmt.Sprintf("_%s = %s", f.Name, f.Name))
		}
	}
	inits = append(inits, "super._(instance, cause, null)")
	g.p("      : %s;", strings.Join(inits, ",\n        "))
	g.p("")

	// parsed constructor
	g.p("  %s._received({", n)
	for _, f := range p.Data {
		if f.Private {
			continue
		}
		if f.Optional {
			g.p("    this.%s,", f.Name)
		} else {
			g.p("    required this.%s,", f.Name)
		}
	}
	g.p("    required rt.Received received,")
	g.p("    String? instance,")
	g.p("  })")
	inits = nil
	for _, f := range p.Data {
		if f.Private {
			inits = append(inits, fmt.Sprintf("_%s = null", f.Name))
		}
	}
	inits = append(inits, "super._(instance, null, received)")
	g.p("      : %s;", strings.Join(inits, ",\n        "))
	g.p("")

	for _, f := range p.Data {
		g.fieldDecl(f, "  ", f.Private)
	}

	g.p("  static const _meta = rt.Meta(")
	g.p("    id: %s,", dartStr(p.ID))
	g.p("    title: %s,", dartStr(p.Title))
	g.p("    status: %d,", p.Status)
	g.p("    recoverable: %v,", p.Recoverable)
	g.p("    platform: %s,", dartStr(g.cfg.Platform))
	g.p("    service: %s,", dartStr(g.cfg.Service))
	g.p("    module: %s,", dartStr(g.m.Def.Module))
	g.p("    version: %s,", dartStr(g.m.Def.Version))
	g.p("  );")
	g.p("")
	g.p("  @override")
	g.p("  rt.Meta get meta => _meta;")
	g.p("")
	g.p("  @override")
	if p.RetryAfter != "" {
		g.p("  int? get retryAfterSeconds => this.%s;", p.RetryAfter)
	} else {
		g.p("  int? get retryAfterSeconds => null;")
	}
	g.p("")
	g.p("  @override")
	g.p("  String detail() {")
	g.p("    final r = _received;")
	g.p("    if (r != null) return r.detail;")
	g.p("    return %s;", g.renderTemplate(p, p.Detail, false))
	g.p("  }")
	g.p("")
	g.p("  /// Renders the log template. It may contain private fields; it is never sent.")
	g.p("  @override")
	g.p("  String logLine() => %s;", g.renderTemplate(p, p.Log, true))
	g.p("")
	pub := p.PublicData()
	g.p("  @override")
	g.p("  bool get hasData => %v;", len(pub) > 0)
	g.p("")
	g.p("  @override")
	if len(pub) == 0 {
		g.p("  void writeData(rt.Writer w) {}")
	} else {
		g.p("  void writeData(rt.Writer w) {")
		g.p("    w.beginObject();")
		cnt := 0
		for _, f := range p.Data {
			g.writeField(f, "this.", "    ", &cnt)
		}
		g.p("    w.endObject();")
		g.p("  }")
	}
	g.p("")
	g.p("  static %s _decode(rt.Envelope e) {", n)
	if len(pub) > 0 {
		g.p("    final m = rt.asObject(e.data ?? const <String, Object?>{});")
	}
	g.p("    return %s._received(", n)
	for _, f := range pub {
		g.p("      %s: %s,", f.Name, g.decodeField(f))
	}
	g.p("      received: rt.Received(e.type, e.detail),")
	g.p("      instance: e.instance.isEmpty ? null : e.instance,")
	g.p("    );")
	g.p("  }")
	g.p("}")
	g.p("")
}

func (g *dartGen) unknown() {
	g.p("/// A received problem this module does not define (another service, another version,")
	g.p("/// an unknown id, or data that does not match). [reason] says which.")
	g.p("final class Unknown extends Problem {")
	g.p("  Unknown._(this.envelope, this.reason)")
	g.p("      : super._(envelope.instance.isEmpty ? null : envelope.instance, null, null);")
	g.p("")
	g.p("  final rt.Envelope envelope;")
	g.p("  final String reason;")
	g.p("")
	g.p("  /// Describes the received problem as far as it is known.")
	g.p("  @override")
	g.p("  rt.Meta get meta {")
	g.p("    final a = envelope.address;")
	g.p("    return rt.Meta(")
	g.p("      id: a?.id ?? '',")
	g.p("      title: envelope.title,")
	g.p("      status: envelope.status,")
	g.p("      recoverable: false,")
	g.p("      platform: a?.platform ?? '',")
	g.p("      service: a?.service ?? '',")
	g.p("      module: a?.module ?? '',")
	g.p("      version: a?.version ?? '',")
	g.p("    );")
	g.p("  }")
	g.p("")
	g.p("  @override")
	g.p("  int? get retryAfterSeconds => null;")
	g.p("")
	g.p("  @override")
	g.p("  String detail() => envelope.detail;")
	g.p("")
	g.p("  @override")
	g.p("  String logLine() => rt.logValue('unknown problem ${envelope.type}: $reason');")
	g.p("")
	g.p("  @override")
	g.p("  String? get receivedType => envelope.type;")
	g.p("")
	g.p("  /// An Unknown is for classification, not re-serialisation: it re-emits no data.")
	g.p("  @override")
	g.p("  bool get hasData => false;")
	g.p("")
	g.p("  @override")
	g.p("  void writeData(rt.Writer w) {}")
	g.p("}")
}

// parseFn emits `static Problem? parse(String body)` inside the sealed class.
func (g *dartGen) parseFn() {
	mod := g.m.Def
	g.p("  /// Reads a received problem. Returns null only when [body] is not an RFC 9457")
	g.p("  /// problem at all; anything this module does not define becomes an [Unknown].")
	g.p("  static Problem? parse(String body) {")
	g.p("    final e = rt.parseEnvelope(body);")
	g.p("    if (e == null) return null;")
	g.p("    final a = e.address;")
	g.p("    if (a == null ||")
	g.p("        a.platform != %s ||", dartStr(g.cfg.Platform))
	g.p("        a.service != %s ||", dartStr(g.cfg.Service))
	g.p("        a.module != %s ||", dartStr(mod.Module))
	g.p("        a.version != %s) {", dartStr(mod.Version))
	g.p("      return Unknown._(e, %s);", dartStr(fmt.Sprintf("not a problem of %s/%s/%s/%s", g.cfg.Platform, g.cfg.Service, mod.Module, mod.Version)))
	g.p("    }")
	g.p("    switch (a.id) {")
	for _, p := range g.m.Problems {
		n := Pascal(p.ID)
		g.p("      case %s:", dartStr(p.ID))
		g.p("        if (e.status != %d) return Unknown._(e, 'status does not match %d');", p.Status, p.Status)
		g.p("        try {")
		g.p("          return %s._decode(e);", n)
		g.p("        } on FormatException catch (x) {")
		g.p("          return Unknown._(e, x.message);")
		g.p("        }")
	}
	g.p("      default:")
	g.p("        return Unknown._(e, 'unknown id \"${a.id}\"');")
	g.p("    }")
	g.p("  }")
}

// publicReach returns the named types a public field of some problem needs (transitively):
// the only types that are ever written to or read from the wire.
func publicReach(m *Module) map[string]bool {
	out := map[string]bool{}
	var visit func(t FieldType)
	visit = func(t FieldType) {
		switch t.Kind {
		case KArray:
			visit(*t.Items)
		case KRef:
			if out[t.Ref] {
				return
			}
			out[t.Ref] = true
			if nt := m.TypeByName(t.Ref); nt != nil && !nt.IsEnum {
				for _, f := range nt.Fields {
					visit(f.Type)
				}
			}
		}
	}
	for _, p := range m.Problems {
		for _, f := range p.PublicData() {
			visit(f.Type)
		}
	}
	return out
}
