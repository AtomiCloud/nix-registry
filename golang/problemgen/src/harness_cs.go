// csLitQ is csLit with every generated type name prefixed by q (e.g. "global::Ns.").
func csLitQ(m *Module, q string, t FieldType, v *JV) string {
	switch t.Kind {
	case KString:
		return csUnits(v.Str)
	case KInteger:
		return v.Num + "L"
	case KInt64:
		if v.GoString() == "-9223372036854775808" {
			return "long.MinValue"
		}
		return v.GoString() + "L"
	case KNumber:
		if v.Kind == 'o' {
			f, _ := v.Get("$float")
			switch f.GoString() {
			case "NaN":
				return "double.NaN"
			case "Infinity":
				return "double.PositiveInfinity"
			case "-Infinity":
				return "double.NegativeInfinity"
			case "-0":
				return "-0.0d"
			}
		}
		f, _ := strconv.ParseFloat(v.Num, 64)
		if math.IsInf(f, 0) {
			return "double.PositiveInfinity"
		}
		return strconv.FormatFloat(f, 'g', -1, 64) + "d"
	case KBoolean:
		return strconv.FormatBool(v.Bool)
	case KDateTime:
		return "__Rt.Decode.ParseDate(" + csString(v.GoString()) + ")"
	case KArray:
		var parts []string
		for _, e := range v.Arr {
			parts = append(parts, csLitQ(m, q, *t.Items, e))
		}
		return "new " + csTypeQ(q, *t.Items) + "[] {" + strings.Join(parts, ", ") + "}"
	case KRef:
		nt := m.TypeByName(t.Ref)
		if nt.IsEnum {
			return q + t.Ref + "." + Pascal(v.GoString())
		}
		return csCtorQ(m, q, nt.Name, nt.Fields, v, nil)
	}
	return "null!"
}
func csCtorQ(m *Module, q, n string, fs []*Field, data *JV, extras []string) string {
	var args, named []string
	opts := append([]string{}, extras...)
	for _, f := range fs {
		v, ok := data.Get(f.Name)
		if !f.Optional {
			args = append(args, csLitQ(m, q, f.Type, v))
		} else if f.Private && ok && v.Kind != 'z' {
			named = append(named, f.Name+": "+csLitQ(m, q, f.Type, v)) // optional private: constructor parameter
		} else if ok && v.Kind != 'z' {
			opts = append(opts, Pascal(f.Name)+" = "+csLitQ(m, q, f.Type, v))
		}
	}
	e := "new " + q + n + "(" + strings.Join(append(args, named...), ", ") + ")"
	if len(opts) > 0 {
		e += " { " + strings.Join(opts, ", ") + " }"
	}
	return e
}
