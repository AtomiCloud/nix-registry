// emitGoBatch is one Go program for every module of a batch: emit prints every case as
// "<key>/<case>"; parse routes each input line to its module's Parse by the key prefix.
func emitGoBatch(cfg *Config, mods []BatchModule) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...); b.WriteByte('\n') }
	w("// Code generated by problemgen conformance batch-emit --lang go. DO NOT EDIT.")
	w("package main")
	w("")
	w("import (")
	w("\t\"bufio\"")
	w("\t\"encoding/json\"")
	w("\t\"fmt\"")
	w("\t\"math\"")
	w("\t\"os\"")
	w("\t\"strings\"")
	w("\t\"time\"")
	w("")
	w("\trt %q", mods[0].Out.Go.Runtime)
	for _, bm := range mods {
		w("\t%s %q", bm.Out.Go.Package, "conftest/gen/"+bm.Out.Go.Package)
	}
	w(")")
	w("")
	w("var _ = math.NaN")
	w("")
	w("func mustTime(s string) time.Time {")
	w("\tt, err := time.Parse(time.RFC3339Nano, s)")
	w("\tif err != nil {")
	w("\t\tpanic(err)")
	w("\t}")
	w("\treturn t")
	w("}")
	w("")
	w("type line struct {")
	w("\tName    string `json:\"name\"`")
	w("\tOK      bool   `json:\"ok\"`")
	w("\tWire    string `json:\"wire,omitempty\"`")
	w("\tLog     string `json:\"log,omitempty\"`")
	w("\tError   string `json:\"error,omitempty\"`")
	w("\tVariant string `json:\"variant,omitempty\"`")
	w("\tRewire  string `json:\"rewire,omitempty\"`")
	w("}")
	w("")
	w("var enc = json.NewEncoder(os.Stdout)")
	w("")
	goMustSite(w)
	w("")
	w("func emit(name string, site rt.Site, mk func() rt.Problem) {")
	w("\tdefer func() {")
	w("\t\tif r := recover(); r != nil { // a vector the runtime must refuse can panic while it is built (a bad date-time)")
	w("\t\t\t_ = enc.Encode(line{Name: name, Error: fmt.Sprint(r)})")
	w("\t\t}")
	w("\t}()")
	w("\tp := mk()")
	w("\tb, err := rt.Marshal(p, site)")
	w("\tif err != nil {")
	w("\t\t_ = enc.Encode(line{Name: name, Error: err.Error()})")
	w("\t\treturn")
	w("\t}")
	w("\t_ = enc.Encode(line{Name: name, OK: true, Wire: string(b), Log: p.LogLine()})")
	w("}")
	w("")
	w("func reemit(name string, site rt.Site, p rt.Problem) {")
	w("\tb, err := rt.Marshal(p, site)")
	w("\tl := line{Name: name, OK: err == nil, Variant: p.ProblemMeta().ID, Rewire: string(b)}")
	w("\tif err != nil {")
	w("\t\tl.Error = err.Error()")
	w("\t}")
	w("\t_ = enc.Encode(l)")
	w("}")
	w("")
	w("var parsers = map[string]func(name string, wire []byte){")
	for _, bm := range mods {
		pkg := bm.Out.Go.Package
		w("\t%q: func(name string, wire []byte) {", bm.Key)
		w("\t\tp, err := %s.Parse(wire)", pkg)
		w("\t\tif err != nil {")
		w("\t\t\t_ = enc.Encode(line{Name: name, Variant: \"not-problem\", Error: err.Error()})")
		w("\t\t\treturn")
		w("\t\t}")
		w("\t\tif u, ok := p.(*%s.Unknown); ok {", pkg)
		w("\t\t\t_ = enc.Encode(line{Name: name, Variant: \"unknown\", Error: u.Reason})")
		w("\t\t\treturn")
		w("\t\t}")
		w("\t\treemit(name, mustSite(%q, %q), p)", bm.V.Portal, bm.V.Landscape)
		w("\t},")
	}
	w("}")
	w("")
	w("func parse(path string) {")
	w("\tf, err := os.Open(path)")
	w("\tif err != nil {")
	w("\t\tpanic(err)")
	w("\t}")
	w("\tsc := bufio.NewScanner(f)")
	w("\tsc.Buffer(make([]byte, 1<<20), 1<<26)")
	w("\tfor sc.Scan() {")
	w("\t\tvar in struct{ Name, Wire string }")
	w("\t\tif err := json.Unmarshal(sc.Bytes(), &in); err != nil {")
	w("\t\t\tpanic(err)")
	w("\t\t}")
	w("\t\tkey, _, _ := strings.Cut(in.Name, \"/\")")
	w("\t\tif fn, ok := parsers[key]; ok {")
	w("\t\t\tfn(in.Name, []byte(in.Wire))")
	w("\t\t}")
	w("\t}")
	w("}")
	w("")
	w("func main() {")
	w("\tenc.SetEscapeHTML(false)")
	w("\tif len(os.Args) > 2 && os.Args[1] == \"parse\" {")
	w("\t\tparse(os.Args[2])")
	w("\t\treturn")
	w("\t}")
	for _, bm := range mods {
		for _, c := range bm.V.Cases {
			w("\temit(%q, mustSite(%q, %q), func() rt.Problem { return %s })", bm.Key+"/"+c.Name, bm.V.Portal, bm.V.Landscape, goCaseExpr(bm.M, bm.Out.Go.Package, c))
		}
	}
	w("}")
	return b.String()
}

// goMustSite writes the harness helper that builds the run-time site (portal + landscape).
func goMustSite(w func(string, ...any)) {
	w("func mustSite(portal, landscape string) rt.Site {")
	w("\ts, err := rt.NewSite(portal, landscape)")
	w("\tif err != nil {")
	w("\t\tpanic(err)")
	w("\t}")
	w("\treturn s")
	w("}")
}
