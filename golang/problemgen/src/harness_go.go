func goCaseExpr(m *Module, pkg string, c VCase) string {
	var p *Problem
	for _, q := range m.Problems {
		if q.ID == c.Problem {
			p = q
		}
	}
	data := c.Data
	if data == nil {
		data = &JV{Kind: 'o'}
	}
	e := goCtor(m, pkg, Pascal(p.ID), p.Data, data)
	if c.Instance != "" {
		e += ".WithInstance(" + strconv.Quote(c.Instance) + ")"
	}
	return e
}

