func TestDeltaKeepsLiveOwnerAfterGitImport(t *testing.T) {
	t.Setenv("GIT_CONFIG_GLOBAL", os.DevNull)
	t.Setenv("GIT_CONFIG_NOSYSTEM", "1")
	root := t.TempDir()
	t.Chdir(root)
	gen2Write(t, root, "apps/shop/package.json", "{\"name\":\"shop\"}")
	gen2Write(t, root, "apps/shop/ops/telemetry/contract.yaml", "service: telemetry\nlogs: {Failed: {event: telemetry.failed, level: error}}\ngenerate: [{lang: bun, out: gen/telemetry}]\n")
	gen2Write(t, root, "observability/current/contract.yaml", "service: current\n")
	if rc, out := obs("gen", "--dir", "apps/shop/ops/telemetry"); rc != 0 {
		t.Fatalf("setup gen: rc=%d %s", rc, out)
	}
	file := filepath.Join(root, "apps/shop/ops/gen/telemetry/signals.ts")
	before, err := os.ReadFile(file)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(before), "// contract: ops/telemetry/contract.yaml\n") {
		t.Fatalf("unexpected header: %.180s", before)
	}
	releaseGit(t, root, "init", "-q")
	if rc, out := obs("gen", "--dir", "observability/current"); rc != 0 {
		t.Fatalf("setup current gen: rc=%d %s", rc, out)
	}
	if rc, out := obs("gen", "--check", "--all"); rc != 0 {
		t.Errorf("live owner in import called orphan: rc=%d %s", rc, out)
	}
	rc, out := obs("gen", "--all")
	if rc != 0 {
		t.Errorf("gen --all: rc=%d %s", rc, out)
	}
	if _, err := os.Stat(file); err != nil {
		t.Errorf("live imported Bun output deleted: %v\n%s", err, out)
	}
}

func TestDeltaInvalidLangCannotDeleteOrphans(t *testing.T) {
	root := repo(t, map[string]string{"observability/current/contract.yaml": "service: current\n"})
	t.Chdir(root)
	file := filepath.Join(root, "orphan.yaml")
	for _, lang := range []string{"bogus", "go,"} {
		gen2Write(t, root, "orphan.yaml", "# generated by obs gen from observability/gone/contract.yaml\n# contract-hash: sha256:"+strings.Repeat("0", 64)+"\nmetrics: []\n")
		rc, out := obs("gen", "--all", "--lang="+lang)
		if rc != 2 || !strings.Contains(out, "no generator") {
			t.Errorf("invalid lang accepted: rc=%d %s", rc, out)
		}
		if _, err := os.Stat(file); err != nil {
			t.Errorf("invalid lang deleted file: %v\n%s", err, out)
		}
		if _, err := os.Stat(filepath.Join(root, "observability/current/contract")); !os.IsNotExist(err) {
			t.Errorf("invalid language wrote live contract outputs: %v", err)
		}
	}
	if rc, out := obs("gen", "--all", "--lang=bogus", "--dir", filepath.Join(t.TempDir(), "missing")); rc != 2 || !strings.Contains(out, "no generator") {
		t.Errorf("language validation must precede root discovery: rc=%d %s", rc, out)
	}
}

func TestDeltaPreservesSingleDirWithUnrelatedRootLink(t *testing.T) {
	root := repo(t, map[string]string{"observability/base/contract.yaml": "service: base\n", "observability/base/seed.yaml": releaseSeed})
	t.Chdir(root)
	if rc, out := obs("check", "--dir", "observability/base"); rc != 0 {
		t.Fatalf("baseline rc=%d %s", rc, out)
	}
	if err := os.Symlink("missing.yaml", "contract.yaml"); err != nil {
		t.Fatal(err)
	}
	if rc, out := obs("check", "--dir", "observability/base"); rc != 0 {
		t.Errorf("single-dir check affected by unrelated link: rc=%d %s", rc, out)
	}
}

func TestDeltaOrphanLanguageReport(t *testing.T) {
	root := repo(t, map[string]string{"observability/current/contract.yaml": "service: current\n"})
	t.Chdir(root)
	if rc, out := obs("gen", "--all"); rc != 0 {
		t.Fatal(out)
	}
	gen2Write(t, root, "orphan.ts", "// Code generated by obs gen. DO NOT EDIT.\n// contract: observability/gone/contract.yaml\n// contract-hash: sha256:"+strings.Repeat("0", 64)+"\n")
	if rc, out := obs("gen", "--check", "--all", "--lang=go"); rc != 0 || strings.Contains(out, "[gen-orphan]") {
		t.Fatalf("Go-only check included orphaned Bun file: rc=%d %s", rc, out)
	}
	if rc, out := obs("gen", "--check", "--all"); rc != 1 || !strings.Contains(out, "orphan.ts") || !strings.Contains(out, "[gen-orphan]") {
		t.Fatalf("unfiltered check missed orphaned Bun file: rc=%d %s", rc, out)
	}
}
