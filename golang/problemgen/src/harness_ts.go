// tsLit renders a vector value as a TypeScript expression of the generated type.
func tsLit(m *Module, t FieldType, v *JV) string {
	switch t.Kind {
	case KString:
		return tsQuoteUnits(v.Str)
	case KInteger:
		return v.Num
	case KInt64:
		return v.GoString() + "n"
	case KNumber:
		if v.Kind == 'o' {
			f, _ := v.Get("$float")
			switch f.GoString() {
			case "NaN":
				return "NaN"
			case "Infinity":
				return "Infinity"
			case "-Infinity":
				return "-Infinity"
			case "-0":
				return "-0"
			}
		}
		f, _ := strconv.ParseFloat(v.Num, 64)
		if math.IsInf(f, 1) {
			return "Infinity"
		}
		if math.IsInf(f, -1) {
			return "-Infinity"
		}
		return strconv.FormatFloat(f, 'g', -1, 64)
	case KBoolean:
		return strconv.FormatBool(v.Bool)
	case KDateTime:
		s := v.GoString()
		if tm, err := parseCanonicalDateTime(s); err == nil {
			s = formatDateTime(tm)
		}
		return "new Date(" + strconv.Quote(s) + ")"
	case KArray:
		var parts []string
		for _, e := range v.Arr {
			parts = append(parts, tsLit(m, *t.Items, e))
		}
		return "[" + strings.Join(parts, ", ") + "]"
	case KRef:
		nt := m.TypeByName(t.Ref)
		if nt.IsEnum {
			return tsQuote(v.GoString())
		}
		return tsObject(m, nt.Fields, v, nil)
	}
	return "undefined"
}

// tsObject renders `{ a: ..., b: ... }` with required fields and the present optionals.
func tsObject(m *Module, fields []*Field, data *JV, extra []string) string {
	var parts []string
	for _, f := range fields {
		v, ok := data.Get(f.Name)
		if !ok || v.Kind == 'z' {
			continue // absent (an absent required field would be a compile error: intended)
		}
		parts = append(parts, f.Name+": "+tsLit(m, f.Type, v))
	}
	parts = append(parts, extra...)
	if len(parts) == 0 {
		return "{}"
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

func tsCaseExpr(m *Module, ns string, c VCase) string {
	var p *Problem
	for _, q := range m.Problems {
		if q.ID == c.Problem {
			p = q
		}
	}
	data := c.Data
	if data == nil {
		data = &JV{Kind: 'o'}
	}
	var extra []string
	if c.Instance != "" {
		extra = append(extra, "instance: "+tsQuote(c.Instance))
	}
	return "new " + ns + "." + Pascal(p.ID) + "(" + tsObject(m, p.Data, data, extra) + ")"
}

func emitTSHarness(m *Module, cfg *Config, o Outputs, v *Vectors) string {
	// The harness is written to <project>/main.ts, where <project> is the first path
	// component of the configured output file; the generated file is imported relative to it.
	file := o.TypeScript.File
	rel := file
	if i := strings.Index(file, "/"); i >= 0 {
		rel = file[i+1:]
	}
	rel = strings.TrimSuffix(rel, path.Ext(rel))
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...); b.WriteByte('\n') }
	w("// Code generated by problemgen conformance emit --lang ts. DO NOT EDIT.")
	w("import { readFileSync } from \"node:fs\";")
	w("import * as rt from %s;", tsQuote(o.TypeScript.Runtime))
	w("import * as gen from %s;", tsQuote("./"+rel))
	w("")
	w("const site = rt.Site.of(%s, %s);", tsQuote(v.Portal), tsQuote(v.Landscape))
	w("")
	w("const out: string[] = [];")
	w("const line = (o: Record<string, unknown>): void => {")
	w("  out.push(JSON.stringify(o) + \"\\n\");")
	w("};")
	w("const message = (e: unknown): string => (e instanceof Error ? e.message : String(e));")
	w("")
	// Only with origins: an unused helper fails the strict TS build.
	if len(v.Origins.Accepted)+len(v.Origins.Refused) > 0 {
		w("function emitAt(name: string, portal: string, landscape: string, mk: () => gen.Problem): void {")
		w("  try {")
		w("    const s = rt.Site.of(portal, landscape);")
		w("    const p = mk();")
		w("    line({ name, ok: true, wire: rt.marshal(p, s), log: p.logLine() });")
		w("  } catch (e) {")
		w("    line({ name, ok: false, error: message(e) });")
		w("  }")
		w("}")
		w("")
	}
	w("function emit(name: string, mk: () => gen.Problem): void {")
	w("  try {")
	w("    const p = mk();")
	w("    const wire = rt.marshal(p, site);")
	w("    line({ name, ok: true, wire, log: p.logLine() });")
	w("  } catch (e) {")
	w("    line({ name, ok: false, error: message(e) });")
	w("  }")
	w("}")
	w("")
	w("function parse(file: string): void {")
	w("  for (const raw of readFileSync(file, \"utf8\").split(\"\\n\")) {")
	w("    if (raw.trim() === \"\") continue;")
	w("    const input = JSON.parse(raw) as { name: string; wire: string };")
	w("    const p = gen.parse(input.wire);")
	w("    if (p.kind === \"not-problem\") {")
	w("      line({ name: input.name, ok: false, variant: \"not-problem\", error: p.reason });")
	w("    } else if (p.kind === \"unknown\") {")
	w("      line({ name: input.name, ok: false, variant: \"unknown\", error: p.reason });")
	w("    } else {")
	w("      try {")
	w("        line({ name: input.name, ok: true, variant: p.meta.id, rewire: rt.marshal(p, site) });")
	w("      } catch (e) {")
	w("        line({ name: input.name, ok: false, variant: p.meta.id, error: message(e) });")
	w("      }")
	w("    }")
	w("  }")
	w("}")
	w("")
	w("function bench(n: number): void {")
	w("  const cases: [string, () => gen.Problem][] = [")
	for _, c := range v.Cases {
		if c.Name == "generic-entity-not-found" || c.Name == "every-basic" {
			w("    [%s, () => %s],", tsQuote(c.Name), tsCaseExpr(m, "gen", c))
		}
	}
	w("  ];")
	w("  for (const [name, mk] of cases) {")
	w("    for (let i = 0; i < n / 10; i++) rt.marshal(mk(), site); // warm-up")
	w("    const bytes = new TextEncoder().encode(rt.marshal(mk(), site)).length;")
	w("    let total = 0;")
	w("    const start = process.hrtime.bigint();")
	w("    for (let i = 0; i < n; i++) total += rt.marshal(mk(), site).length;")
	w("    const el = Number(process.hrtime.bigint() - start);")
	w("    if (total <= 0) throw new Error(\"unreachable\");")
	w("    line({ lang: \"ts\", case: name, n, nsPerOp: Math.round((el / n) * 10) / 10, bytes });")
	w("  }")
	w("}")
	w("")
	w("const args = process.argv.slice(2);")
	w("if (args[0] === \"parse\" && args[1] !== undefined) {")
	w("  parse(args[1]);")
	w("} else if (args[0] === \"bench\") {")
	w("  bench(1_000_000);")
	w("} else {")
	for _, c := range v.Cases {
		w("  emit(%s, () => %s);", tsQuote(c.Name), tsCaseExpr(m, "gen", c))
	}
	if c, _, ok := originBase(m, cfg, v); ok {
		for i, o := range v.Origins.Accepted {
			w("  emitAt(%s, %s, %s, () => %s);", tsQuote(originName("ok", i)), tsQuote(o), tsQuote(v.Landscape), tsCaseExpr(m, "gen", c))
		}
		for i, o := range v.Origins.Refused {
			w("  emitAt(%s, %s, %s, () => %s);", tsQuote(originName("refused", i)), tsQuote(o), tsQuote(v.Landscape), tsCaseExpr(m, "gen", c))
		}
	}
	w("}")
	w("process.stdout.write(out.join(\"\"));")
	return b.String()
}

func init() { batchHarnesses["ts"] = emitTSBatch }

// emitTSBatch is one TypeScript program (<project>/main.ts) for every module of a batch.
func emitTSBatch(cfg *Config, mods []BatchModule) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...); b.WriteByte('\n') }
	w("// Code generated by problemgen conformance batch-emit --lang ts. DO NOT EDIT.")
	w("import { readFileSync } from \"node:fs\";")
	w("import * as rt from %s;", tsQuote(mods[0].Out.TypeScript.Runtime))
	for _, bm := range mods {
		file := bm.Out.TypeScript.File
		rel := file
		if i := strings.Index(file, "/"); i >= 0 {
			rel = file[i+1:]
		}
		rel = strings.TrimSuffix(rel, path.Ext(rel))
		w("import * as m_%s from %s;", bm.Key, tsQuote("./"+rel))
	}
	w("")
	w("const out: string[] = [];")
	w("const line = (o: Record<string, unknown>): void => {")
	w("  out.push(JSON.stringify(o) + \"\\n\");")
	w("};")
	w("const message = (e: unknown): string => (e instanceof Error ? e.message : String(e));")
	w("")
	w("function emit(name: string, site: rt.Site, mk: () => rt.ProblemValue): void {")
	w("  try {")
	w("    const p = mk();")
	w("    const wire = rt.marshal(p, site);")
	w("    line({ name, ok: true, wire, log: p.logLine() });")
	w("  } catch (e) {")
	w("    line({ name, ok: false, error: message(e) });")
	w("  }")
	w("}")
	w("")
	w("function reemit(name: string, site: rt.Site, p: rt.ProblemValue): void {")
	w("  try {")
	w("    line({ name, ok: true, variant: p.meta.id, rewire: rt.marshal(p, site) });")
	w("  } catch (e) {")
	w("    line({ name, ok: false, variant: p.meta.id, error: message(e) });")
	w("  }")
	w("}")
	w("")
	w("const parsers: Record<string, (name: string, wire: string) => void> = {")
	for _, bm := range mods {
		w("  %s: (name, wire) => {", tsQuote(bm.Key))
		w("    const p = m_%s.parse(wire);", bm.Key)
		w("    if (p.kind === \"not-problem\") line({ name, ok: false, variant: \"not-problem\", error: p.reason });")
		w("    else if (p.kind === \"unknown\") line({ name, ok: false, variant: \"unknown\", error: p.reason });")
		w("    else reemit(name, rt.Site.of(%s, %s), p);", tsQuote(bm.V.Portal), tsQuote(bm.V.Landscape))
		w("  },")
	}
	w("};")
	w("")
	w("function parse(file: string): void {")
	w("  for (const raw of readFileSync(file, \"utf8\").split(\"\\n\")) {")
	w("    if (raw.trim() === \"\") continue;")
	w("    const input = JSON.parse(raw) as { name: string; wire: string };")
	w("    const fn = parsers[input.name.split(\"/\")[0] ?? \"\"];")
	w("    if (fn !== undefined) fn(input.name, input.wire);")
	w("  }")
	w("}")
	w("")
	w("const args = process.argv.slice(2);")
	w("if (args[0] === \"parse\" && args[1] !== undefined) {")
	w("  parse(args[1]);")
	w("} else {")
	for _, bm := range mods {
		for _, c := range bm.V.Cases {
			w("  emit(%s, rt.Site.of(%s, %s), () => %s);", tsQuote(bm.Key+"/"+c.Name), tsQuote(bm.V.Portal), tsQuote(bm.V.Landscape), tsCaseExpr(bm.M, "m_"+bm.Key, c))
		}
	}
	w("}")
	w("process.stdout.write(out.join(\"\"));")
	return b.String()
}
